import type { RatePair, RateQuote, RateSource } from '@nemo/core';

/**
 * Несколько источников курса как один.
 *
 * Провайдеры делят справочник не по договорённости, а по природе: биржа
 * котирует криптовалютную сторону, центральный банк — фиатную, и пара,
 * которую знает один, второму неизвестна. Поэтому цепочка спрашивает по
 * очереди и отдаёт первый непустой ответ, а не сравнивает цены: выбирать
 * не из чего, у пары есть ровно один источник.
 *
 * Порядок при этом значим и задан один раз, при сборке приложения:
 * если пару когда-нибудь начнут котировать оба, брать нужно рыночную
 * цену, а не опорную. Поэтому биржа стоит первой.
 *
 * Отметка времени показанного курса ищется у каждого источника в его
 * собственных снимках. Чужую он не найдёт и ответит текущей ценой —
 * ровно так же, как на отметку, вымытую из памяти. Спутать источники
 * этим нельзя: пару, которой у провайдера нет, он не котирует ни на
 * какую отметку.
 */
export function createChainRateSource(sources: readonly RateSource[]): RateSource {
  return {
    async quote(pair: RatePair, at?: Date): Promise<RateQuote | null> {
      for (const source of sources) {
        const quote = await source.quote(pair, at);
        if (quote) return quote;
      }
      return null;
    },
  };
}
