/**
 * Кэш снимков внешнего источника — общий для всех провайдеров курса.
 *
 * Правило у них одно и то же, и оно не про котировки, а про чужой
 * сервер: устаревшее отдаётся сразу, а за свежим уходят в фоне. Запрос
 * клиента не должен стоять в очереди за биржей — она отвечает от долей
 * секунды до десятков, и поставить её в путь ответа значит отдать ей
 * скорость приложения.
 *
 * Отсюда же и снимки во множественном числе: клиент подаёт заявку по
 * курсу, который увидел, и присылает отметку его времени. Ответить
 * именно тем курсом можно, только храня несколько снимков, — между
 * показом и нажатием кэш успевает обновиться.
 *
 * Провайдеров два, и логика ожидания у них одинаковая: живя в каждом
 * своей копией, она разошлась бы при первой же правке — а правка здесь
 * означает «кто-то ждёт чужой сервер дольше, чем думает».
 */

export interface Snapshot<T> {
  readonly at: number;
  readonly value: T;
}

export interface SnapshotCacheOptions<T> {
  /** Сходить к провайдеру. Ошибки не глушит: их обрабатывает кэш. */
  readonly load: () => Promise<T>;
  /** Через сколько снимок считается устаревшим и просит обновления. */
  readonly ttlMs: number;
  /** Насколько старый снимок ещё можно показывать, пока провайдер молчит. */
  readonly maxAgeMs: number;
  /**
   * Насколько старую отметку показанного курса принимает подача.
   *
   * Срок свой, а не `maxAgeMs`: тот отвечает на молчание провайдера, а
   * отметку присылает клиент. Потолок показа в час, распространившись
   * на отметку, дал бы час выбора — держать показанный курс и подать
   * заявку тогда, когда рынок ушёл дальше наценки. Между взглядом и
   * нажатием проходят минуты; отметка старше срока просто откатывается
   * на текущий курс, как и незнакомая.
   */
  readonly quotedAgeMs?: number;
  /**
   * Сколько снимков помнить ради отметок времени в поданных заявках.
   *
   * По умолчанию — ровно столько, чтобы память покрывала весь срок, в
   * течение которого отметка ещё принимается: обновление приходит раз
   * в `ttlMs`, отметка живёт `quotedAgeMs`, и на краю нужен ещё
   * один. Заданное числом покрытие расходится с этим сроком молча: у
   * заявки, поданной по курсу пятиминутной давности, снимок оказывался
   * вытеснен, и она уходила по текущему курсу — то есть не по тому,
   * который клиент видел.
   */
  readonly keep?: number;
  /** Чьё молчание попадёт в журнал. */
  readonly provider: string;
  /**
   * Сколько раз прогрев пробует достучаться до провайдера.
   *
   * Больше одного, потому что провайдер отвечает рвано: у биржи замерено
   * от 0,15 до 12 секунд, а срок запроса — три. Одна попытка попадает на
   * медленный ответ и срывается, и тогда первый клиент видит «курс
   * назовёт менеджер» на пустом кэше — при том, что биржа жива.
   */
  readonly warmUpAttempts?: number;
  /**
   * Пауза перед следующей попыткой прогрева; растёт с её номером. Лежачий
   * провайдер не оживает от того, что в него стучат чаще.
   */
  readonly warmUpRetryMs?: number;
  /**
   * Сколько ждать запрос, который не завершается ни ответом, ни отказом,
   * прежде чем бросить его.
   *
   * Такое бывает: 27 августа 2026 на боевом запрос к провайдеру завис
   * посреди сетевого сбоя — не ответил, не отказал, и срок запроса у
   * провайдера не сработал. Один запрос на всех означал, что вместе с
   * ним девять часов ждали все клиенты и все тики таймера; в журнал не
   * попало ни строки, потому что отказа не было. Потолок стоит выше
   * срока запроса у любого провайдера — обычный отказ приходит раньше —
   * и означает не «провайдер молчит», а «запрос потерян»: он бросается
   * с записью в журнал, а следующее обновление идёт заново.
   */
  readonly stallMs?: number;
  /** Подменяется в тестах, чтобы проверить устаревание. */
  readonly now?: () => number;
}

/**
 * Четыре попытки с растущей паузой — это около двенадцати секунд, за
 * которые провайдер должен ответить хоть раз. Первый клиент приходит
 * заметно позже: между выкаткой и им проходит хотя бы столько же.
 */
const DEFAULT_WARM_UP_ATTEMPTS = 4;
const DEFAULT_WARM_UP_RETRY_MS = 2_000;

/**
 * Потолок ожидания одного запроса. В пять раз больше срока запроса у
 * провайдеров (три секунды): попасть под него может только запрос,
 * который потерян, а не медленный.
 */
const DEFAULT_STALL_MS = 15_000;

/**
 * Срок отметки по умолчанию — прежний потолок показа. Пять минут
 * держали окно между взглядом и нажатием до того, как потолок вырос до
 * часа ради молчащего провайдера, и на отметке им вырасти нельзя.
 */
const DEFAULT_QUOTED_AGE_MS = 5 * 60_000;

export interface SnapshotCache<T> {
  /**
   * Что показывать прямо сейчас — или что показывали в названный
   * момент. Пусто, когда показывать нечего: провайдер молчит с самого
   * запуска или последнее известное слишком старое.
   */
  read(at?: Date): Promise<Snapshot<T> | undefined>;
  /**
   * Сходить за данными, не дожидаясь первого клиента, — и не сдаваться с
   * первого отказа. Ждать прогрев некому, поэтому срок запроса ему не
   * указ: три секунды поставлены, чтобы биржу не ждал человек у экрана,
   * а здесь у экрана никого нет.
   *
   * С прогревом заводится и обновление по таймеру; возвращённая функция
   * останавливает его. Рабочему деплою она ни к чему — там таймер живёт
   * столько же, сколько процесс, — а вот пересозданный кэш без неё
   * оставлял бы за собой стучащий в провайдера сиротский таймер.
   */
  warmUp(): () => void;
}

/**
 * Обещание с потолком: не завершилось в срок — отвергается, а поздний
 * исход самого запроса больше никого не интересует. Таймер отпущен,
 * как и таймер обновления: ждать его процессу незачем.
 */
function withStallCeiling<T>(pending: Promise<T>, ms: number, stalled: () => Error): Promise<T> {
  return new Promise<T>((resolve, reject) => {
    const timer = setTimeout(() => reject(stalled()), ms);
    if (typeof timer === 'object' && 'unref' in timer) timer.unref();
    pending.then(
      (value) => {
        clearTimeout(timer);
        resolve(value);
      },
      (error: unknown) => {
        clearTimeout(timer);
        reject(error instanceof Error ? error : new Error(String(error)));
      },
    );
  });
}

export function createSnapshotCache<T>(options: SnapshotCacheOptions<T>): SnapshotCache<T> {
  const now = options.now ?? Date.now;
  const stallMs = options.stallMs ?? DEFAULT_STALL_MS;
  const quotedAgeMs = options.quotedAgeMs ?? DEFAULT_QUOTED_AGE_MS;
  // Отметка не переживает и потолка показа: память под неё длиннее его
  // была бы памятью под то, что всё равно не отдать.
  const keep =
    options.keep ?? Math.ceil(Math.min(quotedAgeMs, options.maxAgeMs) / options.ttlMs) + 1;

  /** Снимки, новейший последний. */
  const snapshots: Snapshot<T>[] = [];
  let inFlight: Promise<Snapshot<T>> | undefined;
  /**
   * Ждал ли уже кто-нибудь ответа на пустом кэше. Ожидание здесь ровно
   * одно на запуск процесса: пока показывать нечего, второй и третий
   * клиент ничего от своего ожидания не выигрывают.
   */
  let waited = false;
  /**
   * Начинался ли прогрев. Он один на кэш и на запуск процесса: второй
   * завёл бы свою цепочку попыток и удвоил стук в провайдера, у которого
   * есть предел обращений в минуту.
   */
  let warmUpStarted = false;

  const newest = (): Snapshot<T> | undefined => snapshots[snapshots.length - 1];

  /** Одно правило свежести на показ и на фильтр — расходясь, они дали
   * бы снимок, который одна половина кода отдаёт, а другая отсеивает. */
  const showable = (snapshot: Snapshot<T>): boolean => now() - snapshot.at <= options.maxAgeMs;

  /**
   * Обновление, которое никого не ждёт.
   *
   * Один запрос на всех, кто спросил, пока он идёт: даже склеенные,
   * запросы к чужому API нужны раз в срок жизни снимка, а не по числу
   * посетителей.
   */
  function refresh(): Promise<Snapshot<T>> {
    if (inFlight) return inFlight;

    const attempt: Promise<Snapshot<T>> = withStallCeiling(
      options.load(),
      stallMs,
      () =>
        new Error(
          `${options.provider}: запрос не завершился за ${stallMs / 1000} с ни ответом, ни отказом — брошен`,
        ),
    )
      .then((value) => {
        const snapshot: Snapshot<T> = { at: now(), value };
        snapshots.push(snapshot);
        if (snapshots.length > keep) snapshots.shift();
        /*
         * Провайдер ответил — значит он жив, и следующего клиента,
         * пришедшего на протухший снимок, снова стоит заставить
         * подождать. Признак, поставленный навсегда, означал бы, что
         * одно давнее молчание биржи навсегда лишает ожидания всех
         * последующих.
         */
        waited = false;
        return snapshot;
      })
      .finally(() => {
        // Место освобождается только за собой: брошенный запрос
        // освобождает его раньше, и к этому моменту оно может быть
        // занято следующим.
        if (inFlight === attempt) inFlight = undefined;
      });
    inFlight = attempt;
    return attempt;
  }

  /**
   * Обновление, за которым никто не смотрит. Причина — в журнал: пути
   * сюда разные, и неразличимые записи не дали бы понять, било ли
   * молчание провайдера по ждущему клиенту или прошло фоном.
   */
  function refreshQuietly(reason: string): void {
    void refresh().catch((error: unknown) => {
      console.error(`${options.provider} не ответила (${reason})`, error);
    });
  }

  async function current(): Promise<Snapshot<T> | undefined> {
    const known = newest();
    // Показывать нечего: снимка нет вовсе или он старше того срока, на
    // который сервис готов за него отвечать. Разницы для клиента между
    // этими двумя случаями никакой — в обоих он остаётся без курса.
    if (known === undefined || !showable(known)) {
      if (inFlight) {
        /*
         * Запрос уже идёт — дождаться его. Ответ у всех общий, и пусто
         * вместо него получали бы из-за очереди у признака, а не у
         * провайдера: бот спрашивает все направления разом, и у рублёвых
         * пар кэш один — первый уходил ждать, остальные возвращались ни
         * с чем, доска выходила дырявой.
         */
        try {
          return await inFlight;
        } catch {
          // Отказ уже записан тем, кто запрос запускал.
          return undefined;
        }
      }

      if (waited) {
        /*
         * Ждали и не дождались. Новых ожиданий не заводится: пока
         * провайдер лежит, каждый следующий клиент платил бы своим
         * сроком зря — ответ один и тот же. Обновление уходит в фон, и
         * первый удавшийся запрос вернёт курс всем сразу.
         */
        refreshQuietly('пинок после отказа, клиент ушёл без курса');
        return undefined;
      }

      if (known) {
        /*
         * Снимок пережил свой срок, а обновиться было некому. С фоновым
         * обновлением это означает, что провайдер молчал весь его срок,
         * — событие редкое, и потому заметное в журнале, а не тонущее в
         * шуме. До того, как оно появилось, о пропаже курса в логах не
         * было ни строки, и жалобу нечем было проверить.
         */
        console.warn(`${options.provider}: снимок пережил свой срок, курс ждёт обновления`);
      }

      /*
       * Здесь и только здесь клиент ждёт чужой сервер. Ждать доли
       * секунды честнее, чем сказать «курса нет» при живой бирже: до
       * этой правки кэш отдавал протухший снимок, потолок выбрасывал
       * его, и человек получал пустоту, притом что ответ провайдера уже
       * шёл. В рабочем деплое это ожидание съедает прогрев.
       */
      waited = true;
      try {
        return await refresh();
      } catch (error) {
        // Недоступность провайдера — рабочее состояние, а не авария:
        // заявку клиент подаст и без курса, а курс назовёт менеджер.
        console.error(`${options.provider} не ответила (клиент ждал ответа)`, error);
        return undefined;
      }
    }

    if (now() - known.at >= options.ttlMs) {
      // Показ не ждёт: устаревшее отдаётся сразу, свежее придёт следом.
      refreshQuietly('плановое обновление при чтении');
    }
    return known;
  }

  return {
    async read(at?: Date): Promise<Snapshot<T> | undefined> {
      /*
       * Курс, который клиент видел, ищется среди снимков по отметке
       * времени — и только в её собственном сроке: отметку присылает
       * клиент, и без срока она превращалась бы в право выбрать из
       * прошлого выгодный курс. Не нашли или срок вышел — отвечаем
       * текущим: это не повод отказывать в подаче.
       */
      const quoted = at ? snapshots.find((one) => one.at === at.getTime()) : undefined;
      const snapshot =
        quoted && now() - quoted.at <= quotedAgeMs ? quoted : await current();

      // Слишком старое не показывается: по такому курсу подают заявку, а
      // она обязательство сервиса.
      if (!snapshot || !showable(snapshot)) return undefined;
      return snapshot;
    },

    warmUp(): () => void {
      if (warmUpStarted) return () => {};
      warmUpStarted = true;

      const attempts = options.warmUpAttempts ?? DEFAULT_WARM_UP_ATTEMPTS;
      const retryMs = options.warmUpRetryMs ?? DEFAULT_WARM_UP_RETRY_MS;

      void (async () => {
        for (let attempt = 1; attempt <= attempts; attempt += 1) {
          // Снимок мог появиться и без прогрева — от клиента, пришедшего
          // раньше, чем провайдер ответил. Греть тогда нечего.
          if (newest()) return;

          try {
            await refresh();
            return;
          } catch (error) {
            console.error(`${options.provider} не ответила при прогреве`, error);
          }

          if (attempt < attempts) {
            await new Promise((resolve) => setTimeout(resolve, retryMs * attempt));
          }
        }
      })();

      /*
       * И дальше — само, пока процесс жив.
       *
       * Обновление по чужому запросу работает, только когда запросы идут
       * подряд. У сервиса они идут вразбежку — часы между двумя живыми
       * клиентами, — и снимок успевал умереть между ними. Каждый клиент
       * приходил на пустое место и слышал «курс назовёт менеджер» при
       * бирже, которая отвечает за две десятых секунды.
       *
       * Заводится таймер независимо от того, чем кончился прогрев:
       * провайдер, лежавший в минуту запуска, иначе не ожил бы до первого
       * клиента — то есть до того самого, ради которого всё и делается.
       */
      const timer = setInterval(() => {
        /*
         * Снимок моложе половины срока не обновляется: за новым только
         * что сходило чтение на границе срока или затянувшийся прошлый
         * тик, и стучать в провайдера ради того, что есть, незачем.
         * Половина, а не весь срок: провайдер отвечает не мгновенно, и
         * снимок на тике всегда чуть моложе срока — сверяясь со всем
         * сроком, тик пропускал бы каждый второй раз и обновление
         * выходило бы вдвое реже обещанного.
         */
        const known = newest();
        if (known && now() - known.at < options.ttlMs / 2) return;
        refreshQuietly('обновление по таймеру');
      }, options.ttlMs);

      /*
       * Таймер отпущен: процесс, которому пора закончиться, не должен
       * ждать следующего обновления курса — ждал бы он его вечно.
       */
      if (typeof timer === 'object' && 'unref' in timer) timer.unref();

      return () => clearInterval(timer);
    },
  };
}
