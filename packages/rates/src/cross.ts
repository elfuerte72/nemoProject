import type { RatePair, RateQuote, RateSource } from '@nemo/core';
import { Money } from '@nemo/types';

/**
 * Пара, собранная из двух звеньев через опорную валюту.
 *
 * Прямой цены у рубля в батах не существует: рублёвую сторону котирует
 * биржа, тайскую — тайская биржа, и ни одна не знает пару целиком.
 * Сервис при этом идёт этой дорогой на самом деле — продаёт рубли за
 * USDT, покупает на них баты, — поэтому цена собирается тем же путём,
 * которым идут деньги. Так и записано в ТЗ владельца:
 * `RUB → USD → THB`.
 *
 * Это ровно то, чего не делает `rapira.ts`, и разница не в
 * непоследовательности. Провайдер не должен подменять недостающую
 * котировку самодельной: спросили у него — значит хотели его цену.
 * Составление живёт отдельным источником, стоит в цепочке последним и
 * включается только там, где прямой цены нет ни у кого.
 *
 * Опорная валюта — USDT: через неё сервис и работает. Долларом она
 * больше не считается — цену `USDT → USD` называет биржа, — но опорной
 * от этого быть не перестала: путь денег задаёт не курс, а то, за что
 * сервис покупает валюту выдачи.
 */

/** Опорная валюта по умолчанию — та, через которую идут деньги сервиса. */
const DEFAULT_BASE = 'USDT';

export interface CrossRateOptions {
  readonly base?: string;
}

/**
 * `direct` — источник прямых котировок, обычно цепочка провайдеров.
 * Составной обращается к нему дважды и сам в него не входит: иначе
 * первое же составление ушло бы вглубь себя.
 */
export function createCrossRateSource(
  direct: RateSource,
  options: CrossRateOptions = {},
): RateSource {
  const base = (options.base ?? DEFAULT_BASE).toUpperCase();

  return {
    async quote(pair: RatePair, at?: Date): Promise<RateQuote | null> {
      const from = pair.fromCode.toUpperCase();
      const to = pair.toCode.toUpperCase();

      /*
       * Пару, у которой опорная валюта с краю, составлять нечем: одно из
       * звеньев было бы самой этой парой, а её только что спросили у
       * прямых источников — и они промолчали. Второе звено при этом
       * ведёт опорную валюту саму к себе, то есть составление вернуло бы
       * то же самое молчание, сходив за ним дважды.
       */
      if (from === base || to === base || from === to) return null;

      const first = await direct.quote({ fromCode: from, toCode: base }, at);
      if (!first) return null;

      const second = await direct.quote({ fromCode: base, toCode: to }, at);
      if (!second) return null;

      const rate = Money.multiply(first.rate, second.rate);
      /*
       * Ноль означает испорченную котировку у одного из звеньев.
       * Умножение разносит его дальше, и клиент увидел бы «получаю 0» —
       * число, которое выглядит как ответ сервиса. Честнее промолчать:
       * экран тогда скажет, что курс назовёт менеджер.
       */
      if (Money.isZero(rate) || Money.isNegative(rate)) return null;

      return {
        rate,
        /*
         * Отметка старшего из звеньев. Она говорит, на когда цена верна,
         * и составная цена не свежее самой несвежей своей половины —
         * иначе сервис обещал бы свежесть, которой у неё нет. По ней же
         * работает потолок устаревания: слишком старое звено уводит в
         * молчание всю пару.
         */
        asOf: first.asOf <= second.asOf ? first.asOf : second.asOf,
      };
    },
  };
}
