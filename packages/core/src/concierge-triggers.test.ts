import { describe, expect, it } from 'vitest';
import { escalationTrigger } from './concierge-triggers.js';

/**
 * Слова, на которых консьерж замолкает и зовёт человека.
 *
 * Список срабатывает до вызова модели и минует её вовсе. Причина не в
 * экономии: провайдер отвечает рвано, и разговор, в котором клиент
 * говорит «отправил деньги, не пришли», не должен зависеть от того,
 * жива ли сейчас чужая сеть. Это самое дорогое сообщение из всех, что
 * приходят сервису.
 *
 * Ловится смысл, а не буква: у слова берётся основа, потому что клиент
 * пишет «обманули», «обманываете» и «обман» с равной охотой.
 */

describe('деньги, которые не дошли', () => {
  it.each([
    'Отправил деньги час назад, ничего не пришло',
    'оплатил, а средства не поступили',
    'где мои деньги',
  ])('зовёт человека: «%s»', (text) => {
    expect(escalationTrigger(text)).not.toBeNull();
  });
});

describe('обвинение и угроза', () => {
  it.each([
    'вы меня обманули',
    'это мошенники',
    'верните деньги немедленно',
    'напишу жалобу',
    'обращусь в полицию',
    'подам в суд',
  ])('зовёт человека: «%s»', (text) => {
    expect(escalationTrigger(text)).not.toBeNull();
  });
});

describe('наличные', () => {
  // Всё про наличные — строго через менеджера (решение владельца,
  // 10 августа 2026). Промпт дешёвой модели это правило не удержал —
  // на живой пробе она ответила сама, — поэтому оно держится здесь.
  it.each([
    'хочу поменять наличными',
    'можно ли у вас обменять наличные',
    'где выдаёте наличку',
  ])('зовёт человека: «%s»', (text) => {
    expect(escalationTrigger(text)).not.toBeNull();
  });

  it('молчит про безналичный перевод: это не про наличные', () => {
    expect(escalationTrigger('а безналичный перевод как проходит?')).toBeNull();
  });
});

describe('возврат', () => {
  // Возвратами занимается строго менеджер (решение владельца, 10 августа
  // 2026): бот только передаёт. «Верните» ловилось, а «возврат» и
  // «вернуть» — нет.
  it.each([
    'хочу возврат',
    'как оформить возврат денег',
    'можно ли вернуть деньги',
    'вернут ли мне средства',
  ])('зовёт человека: «%s»', (text) => {
    expect(escalationTrigger(text)).not.toBeNull();
  });

  it('молчит про курс, который вернется', () => {
    expect(escalationTrigger('как думаете, курс вернется к 79?')).toBeNull();
  });
});

describe('прямая просьба', () => {
  it.each([
    'позовите менеджера',
    'хочу поговорить с человеком',
    'дайте оператора',
  ])('зовёт человека: «%s»', (text) => {
    expect(escalationTrigger(text)).not.toBeNull();
  });
});

describe('обычный вопрос', () => {
  it.each([
    'какой сегодня курс бата',
    'как вывести баллы',
    'привет, вы работаете по выходным',
    'сколько идёт перевод на карту',
    'можно оплатить отель в Пхукете',
  ])('человека не зовёт: «%s»', (text) => {
    expect(escalationTrigger(text)).toBeNull();
  });
});

describe('ложные срабатывания, которых быть не должно', () => {
  /*
   * Короткая основа внутри чужого слова — главная беда списков такого
   * рода. «Суд» сидит в «посуде» и «судьбе», «вор» в «говорить»: список,
   * ловящий их, уводит к менеджеру каждый второй разговор, и первым это
   * заметит менеджер, а не тест.
   */
  it.each([
    'подскажите про судьбу моей заявки',
    'мне нужно поговорить про курс',
    'а вы принимаете рупии',
  ])('человека не зовёт: «%s»', (text) => {
    expect(escalationTrigger(text)).toBeNull();
  });
});

describe('оформление', () => {
  it('не зависит от регистра', () => {
    expect(escalationTrigger('ВЕРНИТЕ ДЕНЬГИ')).not.toBeNull();
  });

  it('не зависит от «ё»: клиент пишет и так, и так', () => {
    expect(escalationTrigger('перевод не дошёл')).not.toBeNull();
    expect(escalationTrigger('перевод не дошел')).not.toBeNull();
  });

  it('называет причину, а не только факт', () => {
    // Причина уходит менеджеру в сводке: «позвал, потому что клиент
    // говорит про непришедшие деньги» отвечает на вопрос «что случилось»
    // до того, как он откроет переписку.
    expect(escalationTrigger('деньги не пришли')).toEqual(expect.any(String));
  });

  it('молчит на пустом тексте', () => {
    expect(escalationTrigger('')).toBeNull();
    expect(escalationTrigger('   ')).toBeNull();
  });
});
