import { describe, expect, it } from 'vitest';
import { MAX_REPLY_LENGTH, replyComplaints } from './concierge-guard.js';

/**
 * Застава перед ответом консьержа.
 *
 * Модель дешёвая, и разговор идёт про деньги: единственное, чего нельзя
 * допустить, — названное ею число, которого сервис не называл. Курс,
 * сумма и срок, взятые ею из воздуха, читаются клиентом как обещание
 * сервиса, и спорить он потом будет со скриншотом.
 *
 * Поэтому правило простое до грубости: в ответе не бывает числа,
 * которого нет в справке или в словах самого клиента. Модели об этом
 * сказано прямо, а деньги ей велено называть цифрами из справки — но
 * правило держится здесь, а не на её послушании.
 */

/** Справка, какую ядро кладёт в запрос: числа отсюда называть можно. */
const FACTS = 'Курс USDT → RUB: 81,25. Заявка 7 от 6 августа: в работе. Баллов: 1200.';

describe('числа', () => {
  it('пропускает те, что сервис назвал сам', () => {
    expect(
      replyComplaints({
        reply: 'Сейчас курс 81,25 за USDT. По заявке 7 менеджер уже работает.',
        sources: [FACTS],
      }),
    ).toEqual([]);
  });

  it('ловит выдуманный курс', () => {
    const complaints = replyComplaints({
      reply: 'Сейчас курс 95 рублей за USDT.',
      sources: [FACTS],
    });

    expect(complaints).toHaveLength(1);
    expect(complaints[0]).toContain('95');
  });

  it('пропускает то, что назвал сам клиент: он спрашивает про свою сумму', () => {
    expect(
      replyComplaints({
        reply: 'Проверил: заявки на 5000 USDT у вас нет.',
        sources: [FACTS, 'Хочу поменять 5000 USDT'],
      }),
    ).toEqual([]);
  });

  it('не различает незначащий ноль в конце: 81,25 и 81,250 — одно число', () => {
    /*
     * Справка печатает курс с хвостом нулей, а модель его отбрасывает —
     * и законный ответ отвергался как выдуманный. Замечено на живом
     * провайдере 7 августа 2026: справка «78,40», ответ «78,4».
     */
    expect(
      replyComplaints({ reply: 'Курс 81,250 и ещё 78,4.', sources: [FACTS, 'и 78,40'] }),
    ).toEqual([]);
  });

  it('не различает запятую и точку: разделитель — оформление, а не число', () => {
    expect(
      replyComplaints({ reply: 'Курс 81.25.', sources: [FACTS] }),
    ).toEqual([]);
  });

  it('не считает числом разряды, разбитые пробелом', () => {
    expect(
      replyComplaints({ reply: 'На балансе 1 200 баллов.', sources: [FACTS] }),
    ).toEqual([]);
  });

  it('пропускает ответ вовсе без чисел', () => {
    expect(
      replyComplaints({
        reply: 'Курс виден на главном экране обменника, там же и заявка.',
        sources: [FACTS],
      }),
    ).toEqual([]);
  });

  it('называет каждое выдуманное число, а не только первое', () => {
    // Без единиц времени: срок ловится отдельным правилом, и жалоба от
    // него мешала бы считать здесь именно числа.
    const complaints = replyComplaints({
      reply: 'Комиссия 3 процента, курс 95.',
      sources: [FACTS],
    });

    expect(complaints).toHaveLength(2);
  });
});

describe('длина', () => {
  it('ловит ответ длиннее предела: в чате его дочитывают до середины', () => {
    const complaints = replyComplaints({
      reply: 'а'.repeat(MAX_REPLY_LENGTH + 1),
      sources: [FACTS],
    });

    expect(complaints).toHaveLength(1);
    expect(complaints[0]).toContain('длиннее');
  });

  it('пропускает ответ ровно в предел', () => {
    expect(
      replyComplaints({ reply: 'а'.repeat(MAX_REPLY_LENGTH), sources: [FACTS] }),
    ).toEqual([]);
  });
});

describe('пустота', () => {
  it('ловит ответ, в котором нечего читать', () => {
    expect(replyComplaints({ reply: '   ', sources: [FACTS] })).toHaveLength(1);
  });
});

describe('машинный ритм', () => {
  it('ловится тем же правилом, что и рукописные тексты', () => {
    const complaints = replyComplaints({
      reply: 'Курс — цифрой здесь, заявка — у менеджера, ответ — в этом чате.',
      sources: [FACTS],
    });

    expect(complaints).toHaveLength(1);
    expect(complaints[0]).toContain('тире');
  });
});

/**
 * Служебная кухня наружу не выходит.
 *
 * Модель видит справку, правила и сигнальное слово — и пересказывает их
 * клиенту как часть ответа. «В справке указаны только направления»
 * (лента dev-бота, 7 августа 2026) сообщает клиенту, что у сервиса есть
 * какая-то справка, и ничего не отвечает по существу.
 */
describe('служебное', () => {
  it('ловит ссылку на справку', () => {
    const complaints = replyComplaints({
      reply: 'В справке указаны только обменные направления.',
      sources: [FACTS],
    });

    expect(complaints).toHaveLength(1);
    expect(complaints[0]).toContain('справк');
  });

  it('ловит ссылку на предоставленную информацию', () => {
    expect(
      replyComplaints({
        reply: 'Согласно предоставленной информации, заявка в работе.',
        sources: [FACTS],
      }),
    ).not.toEqual([]);
  });

  it('ловит представление себя моделью', () => {
    expect(
      replyComplaints({ reply: 'Я языковая модель и не знаю этого.', sources: [FACTS] }),
    ).not.toEqual([]);
  });

  it('ловит сигнальное слово, уехавшее в текст', () => {
    // Страховка на случай, если источник просьбу не распознал: клиенту
    // это слово не значит ничего.
    expect(
      replyComplaints({ reply: 'Заявка ждёт оплаты.\n\nМЕНЕДЖЕР', sources: [FACTS] }),
    ).not.toEqual([]);
  });
});

/**
 * Кто отвечает. Помощник называет себя помощником: клиент, решивший,
 * что говорит с сотрудником, поверит и обещанию, которого сотрудник не
 * давал. В живом прогоне модель назвалась сотрудником сама.
 */
describe('подлог', () => {
  it('ловит «я сотрудник»', () => {
    expect(
      replyComplaints({ reply: 'Я сотрудник обменника TOBEE.', sources: [FACTS] }),
    ).not.toEqual([]);
  });

  it('ловит «я менеджер»', () => {
    expect(
      replyComplaints({ reply: 'Я менеджер, веду вашу заявку.', sources: [FACTS] }),
    ).not.toEqual([]);
  });

  it('пропускает честное «позову менеджера»', () => {
    expect(
      replyComplaints({ reply: 'Позову менеджера, он ответит здесь же.', sources: [FACTS] }),
    ).toEqual([]);
  });
});

/**
 * Сроки. «Пара минут» — такое же обещание, как «две минуты», а заставе
 * чисел слова невидимы. Обещание срока стоит денег ровно так же, как
 * выдуманный курс.
 */
describe('сроки', () => {
  it('ловит срок, которого сервис не называл', () => {
    const complaints = replyComplaints({
      reply: 'Обычно пара минут. Если задержится, менеджер напишет.',
      sources: [FACTS],
    });

    expect(complaints).toHaveLength(1);
    expect(complaints[0]).toContain('срок');
  });

  it('ловит и срок числом: правило одно на оба вида', () => {
    expect(
      replyComplaints({ reply: 'Займёт около двух часов.', sources: [FACTS] }),
    ).not.toEqual([]);
  });

  it('пропускает срок, который назвал сам сервис', () => {
    expect(
      replyComplaints({
        reply: 'Оплатить нужно за тридцать минут после выдачи реквизитов.',
        sources: ['Срок оплаты заявки: 30 минут.'],
      }),
    ).toEqual([]);
  });

  it('не разоружается словом с единицей внутри: «сотрудники» — не срок', () => {
    // «Сотрудники» несут в себе «дни», «сейчас» — «час». Справка с такими
    // словами не называет сроков, и запрет обязан устоять.
    const complaints = replyComplaints({
      reply: 'Обычно пара минут.',
      sources: ['Сотрудники сервиса отвечают прямо в чате. Котировки сейчас нет.'],
    });

    expect(complaints).toHaveLength(1);
    expect(complaints[0]).toContain('срок');
  });

  it('не принимает за срок слово с единицей внутри', () => {
    expect(
      replyComplaints({
        reply: 'Несколько сотрудников уже видят ваш вопрос.',
        sources: [FACTS],
      }),
    ).toEqual([]);
  });

  it('ловит «полчаса»: срок, записанный одним словом', () => {
    expect(
      replyComplaints({ reply: 'Займёт полчаса.', sources: [FACTS] }),
    ).not.toEqual([]);
  });

  it('пропускает ответ без обещания срока', () => {
    expect(
      replyComplaints({
        reply: 'Заявку возьмёт менеджер, он и назовёт срок.',
        sources: [FACTS],
      }),
    ).toEqual([]);
  });
});

/**
 * Суммы прописью. Застава чисел видит только цифры, и «пятьдесят тысяч
 * рублей» проходит мимо неё с тем же весом обещания, что и «50000».
 * Деньги называются цифрами и только из справки — тогда их есть чем
 * сверить.
 */
describe('суммы словами', () => {
  it('ловит сумму прописью: цифровой заставе она невидима', () => {
    const complaints = replyComplaints({
      reply: 'Переведите пятьдесят тысяч рублей, и заявка уйдёт в работу.',
      sources: [FACTS],
    });

    expect(complaints).toHaveLength(1);
    expect(complaints[0]).toContain('словами');
  });

  it('ловит и малый разряд: «сто долларов» — то же обещание', () => {
    const complaints = replyComplaints({
      reply: 'Выйдет примерно сто долларов.',
      sources: [FACTS],
    });

    expect(complaints).toHaveLength(1);
    expect(complaints[0]).toContain('словами');
  });

  it('ловит десятки: «двадцать USDT»', () => {
    expect(
      replyComplaints({ reply: 'Хватит и двадцати USDT.', sources: [FACTS] }),
    ).not.toEqual([]);
  });

  it('пропускает «тысячи» не про деньги', () => {
    expect(
      replyComplaints({
        reply: 'Таких вопросов тысячи, отвечу и на ваш.',
        sources: [FACTS],
      }),
    ).toEqual([]);
  });

  it('пропускает числительное не при валюте: «требуются рубли» — не сумма', () => {
    expect(
      replyComplaints({
        reply: 'Для этого направления требуются рубли на карте.',
        sources: [FACTS],
      }),
    ).toEqual([]);
  });
});

/**
 * Разметка. В переписке её не набирают: список из трёх пунктов и
 * заголовок жирным — вид документа, а не ответа человека в чате.
 */
describe('разметка', () => {
  it('ловит список', () => {
    expect(
      replyComplaints({
        reply: 'Мы меняем:\n- USDT на рубли\n- рубли на баты',
        sources: [FACTS],
      }),
    ).not.toEqual([]);
  });

  it('ловит жирный заголовок', () => {
    expect(
      replyComplaints({ reply: '**Курс**\nВиден до подачи заявки.', sources: [FACTS] }),
    ).not.toEqual([]);
  });

  it('ловит смайлик', () => {
    expect(
      replyComplaints({ reply: 'Заявка уже у менеджера 👍', sources: [FACTS] }),
    ).not.toEqual([]);
  });

  it('пропускает перенос строки: абзац это не разметка', () => {
    expect(
      replyComplaints({
        reply: 'Заявка уже у менеджера.\n\nОн напишет здесь же.',
        sources: [FACTS],
      }),
    ).toEqual([]);
  });
});
