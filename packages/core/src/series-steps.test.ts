import { describe, expect, it } from 'vitest';
import { InvalidInputError } from './errors.js';
import { SERIES_BUCKETS, requireStep, seriesStart, stepStartOf, stepsBack } from './analytics.js';

/**
 * Шаг ряда: сутки, неделя, месяц, квартал.
 *
 * Календарная арифметика проверяется тестом, а не глазом: неверный шаг
 * виден только на границе года или квартала — то есть четыре раза в
 * год, и первым его замечает мерчант, у которого сентябрь попал в
 * летний столбик.
 *
 * Квартал считается тем же правилом, что `date_trunc('quarter', …)` в
 * базе: январь, апрель, июль, октябрь. Двух правд о границе квартала
 * быть не должно — по одному правилу считается ряд, по другому он
 * подписывается.
 */

describe('начало шага', () => {
  it('квартал начинается в январе, апреле, июле и октябре', () => {
    expect(stepStartOf('2026-01-01', 'quarter')).toBe('2026-01-01');
    expect(stepStartOf('2026-03-31', 'quarter')).toBe('2026-01-01');
    expect(stepStartOf('2026-04-01', 'quarter')).toBe('2026-04-01');
    expect(stepStartOf('2026-09-20', 'quarter')).toBe('2026-07-01');
    expect(stepStartOf('2026-12-31', 'quarter')).toBe('2026-10-01');
  });

  it('прежние шаги считаются как считались', () => {
    expect(stepStartOf('2026-09-20', 'day')).toBe('2026-09-20');
    // Воскресенье принадлежит неделе, начавшейся в понедельник.
    expect(stepStartOf('2026-09-20', 'week')).toBe('2026-09-14');
    expect(stepStartOf('2026-09-20', 'month')).toBe('2026-09-01');
  });
});

describe('шаг из адреса', () => {
  it('квартал — известный шаг', () => {
    expect(requireStep('quarter')).toBe('quarter');
  });

  it('незнакомый отвергается, а не подставляется молча', () => {
    expect(() => requireStep('year' as never)).toThrow(InvalidInputError);
  });
});

describe('сдвиг ряда назад', () => {
  it('днями — по суткам', () => {
    expect(stepsBack('2026-09-20', 'day', 13)).toBe('2026-09-07');
    // Через границу месяца, и февраль високосного года не теряется.
    expect(stepsBack('2024-03-01', 'day', 1)).toBe('2024-02-29');
  });

  it('неделями — по понедельникам', () => {
    expect(stepsBack('2026-09-14', 'week', 11)).toBe('2026-06-29');
  });

  it('месяцами — через границу года', () => {
    expect(stepsBack('2026-09-01', 'month', 11)).toBe('2025-10-01');
  });

  it('кварталами — через две границы года', () => {
    expect(stepsBack('2026-07-01', 'quarter', 7)).toBe('2024-10-01');
  });

  it('нулевой сдвиг оставляет корзину на месте', () => {
    expect(stepsBack('2026-07-01', 'quarter', 0)).toBe('2026-07-01');
  });
});

/*
 * Глубина ряда — свойство шага, а не выбранного наверху периода:
 * квартальными столбиками за неделю сравнивать нечего, а помесячными за
 * год — есть. Так устроен масштаб на биржевом графике: выбирая крупный
 * шаг, человек просит заодно и более длинную историю.
 */
describe('окно ряда', () => {
  it('днями — две недели по сегодняшний день', () => {
    expect(SERIES_BUCKETS.day).toBe(14);
    expect(seriesStart('2026-09-20', 'day')).toBe('2026-09-07');
  });

  it('неделями — двенадцать недель, считая от понедельника текущей', () => {
    expect(seriesStart('2026-09-20', 'week')).toBe('2026-06-29');
  });

  it('месяцами — двенадцать месяцев, считая от первого числа текущего', () => {
    expect(seriesStart('2026-09-20', 'month')).toBe('2025-10-01');
  });

  it('кварталами — восемь кварталов, то есть два года', () => {
    expect(seriesStart('2026-09-20', 'quarter')).toBe('2024-10-01');
  });
});
