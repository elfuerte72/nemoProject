/**
 * Тексты, которыми бот говорит с клиентом.
 *
 * В коде, а не в справочнике: их три, меняются они редко и вместе с
 * тоном всего сервиса — то есть тем же заходом, что и остальные
 * формулировки. Справочник «ключ — текст» с правкой из панели здесь был
 * и убран: администратор им не пользовался, а тексты, не проходящие
 * ревью, расходились с остальным приложением молча.
 */

export const botTextKeys = ['greeting', 'support', 'referral'] as const;
export type BotTextKey = (typeof botTextKeys)[number];

export const BOT_TEXTS: Record<BotTextKey, string> = {
  greeting:
    'Здравствуйте. Это обменник USDT и рублей — переводом или наличными.\n\n' +
    'Курс видно сразу: по нему и обменяем. Открывайте обменник, выбирайте ' +
    'направление и сумму — заявку возьмёт менеджер, а бот напишет на каждом шаге.\n\n' +
    'Кнопки под сообщением: курс — цифрой прямо здесь, ссылка — чтобы позвать ' +
    'знакомых, поддержка — если что-то непонятно. Меню всегда рядом с полем ' +
    'ввода: команда «Главное меню».',
  support:
    'Напишите вопрос прямо сюда, в этот чат. Его прочитает менеджер и ' +
    'ответит здесь же — держать открытым приложение для этого не нужно.',
  referral:
    'Меняю здесь USDT и рубли: курс видно сразу, заявку ведёт менеджер. ' +
    'По этой ссылке — заходите:',
};

export function botText(key: BotTextKey): string {
  return BOT_TEXTS[key];
}
