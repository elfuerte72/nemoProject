/**
 * Источник ответов консьержа.
 *
 * Спрятан за интерфейсом ровно по той же причине, что и источник
 * котировок: какая модель и чей это провайдер — свойство развёртывания,
 * и в правила разговора оно протекать не должно. Реализация живёт в
 * `@nemo/concierge`, как реализации курса — в `@nemo/rates`.
 *
 * Ядро при этом решает всё, что решает: кто он, что ему известно, какие
 * числа он вправе называть и годится ли сказанное для отправки. Наружу
 * уходит собранный запрос, обратно приходит текст — и ничего больше.
 *
 * Молчание провайдера выражается пустым ответом, а не исключением:
 * лежащая модель — обычное дело, а не авария, и разговор клиента с
 * сервисом от неё не зависит. Вместо ответа тогда приходит человек.
 */

export interface ConciergeTurn {
  /** Кто сказал: клиент или сервис — всё равно, консьерж или менеджер. */
  readonly role: 'client' | 'service';
  readonly text: string;
}

export interface ConciergeRequest {
  /**
   * Кто он и как говорит. Живёт в коде и правится ревью: голос сервиса
   * администратору не отдан.
   */
  readonly instructions: string;
  /**
   * Справка: факты о сервисе и о клиенте, собранные ядром. Числа в
   * ответе бывают только отсюда — это проверяется, а не подразумевается.
   */
  readonly facts: string;
  /** Разговор целиком, включая ответы менеджера: их клиенту тоже говорили. */
  readonly conversation: readonly ConciergeTurn[];
  /**
   * Чем не годился прошлый ответ. Пусто в первый раз. «Перепишите» без
   * «что именно не так» даёт второй такой же ответ.
   */
  readonly complaints?: readonly string[] | undefined;
}

export interface ConciergeAnswer {
  readonly reply: string;
  /**
   * Модель просит человека. Список слов ловит то, что нельзя пропустить,
   * а это — то, чего в списке не бывает: «оплата второй день висит».
   */
  readonly needsHuman: boolean;
}

export interface ConciergeSource {
  answer(request: ConciergeRequest): Promise<ConciergeAnswer | null>;
}
