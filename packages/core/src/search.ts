import { sql, type SQL } from 'drizzle-orm';
import { merchants } from '@nemo/db';

/**
 * Поиск по образцу — общий для стола и для списка мерчантов.
 *
 * Живёт отдельным модулем, а не в каждом из них: вопрос у обоих один —
 * «найди по куску названия», — и две копии экранирования разошлись бы
 * на первой правке, оставив одну из выборок открытой для знаков
 * шаблона.
 */

/**
 * Обезвредить знаки поиска по образцу.
 *
 * Процент и подчёркивание в `like` означают «что угодно», и набранный
 * человеком «100%» превратился бы в поиск всего, что начинается на сто.
 * Обратная косая экранируется первой — иначе ею же и обошли бы
 * экранирование.
 */
export function likeEscape(value: string): string {
  return value.replace(/[\\%_]/g, (sign) => `\\${sign}`);
}

/** Кусок, набранный человеком, — в образец `like` вокруг него. */
export function likePattern(value: string): string {
  return `%${likeEscape(value.trim())}%`;
}

/**
 * Название мерчанта без учёта регистра — с явной коллацией ICU.
 *
 * Обычный `ilike` регистр кириллицы не понимает: база сервиса собрана
 * с локалью `C`, и «Оплатишка» на запрос «оплат» не находится вовсе.
 * Ник клиента этим не задет — он латиницей, — а название мерчанта
 * русское, и менеджер набирает его как придётся.
 *
 * Коллация есть у Postgres, собранного с ICU: так собран официальный
 * образ, на котором сервис и работает (README, «Запуск»).
 */
export function merchantNameLike(pattern: string): SQL {
  return sql`${merchants.name} collate "und-x-icu" ilike ${pattern}`;
}
