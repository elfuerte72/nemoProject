/**
 * Источник черновика статей для базы знаний.
 *
 * Администратор приносит документ — регламент, памятку, ответы на
 * частые вопросы, — а статьи из него делает модель. Спрятана она за
 * интерфейсом по той же причине, что и источник ответов консьержа:
 * чья модель и какая — свойство развёртывания. Реализация живёт в
 * `@nemo/concierge` рядом с консьержем — провайдер у них один.
 *
 * Отдельный интерфейс, а не второй метод консьержа: «есть консьерж» у
 * ядра означает «клиенту отвечает модель», и панель, получившая
 * консьержа ради разбора документов, стала бы им притворяться.
 *
 * Ядро решает, что считать статьёй и что с ней делать дальше: наружу
 * уходит инструкция редактора и текст, обратно — названия с текстами.
 * Молчание провайдера выражается `null`, а не исключением: модель лежит
 * регулярно, и это не авария — администратор повторит разбор позже.
 */

export interface KnowledgeDraftRequest {
  /** Кто он и что считать статьёй. Живёт в коде и проходит ревью. */
  readonly instructions: string;
  /** Текст документа, уже вытащенный из файла. */
  readonly text: string;
}

export interface DraftedArticle {
  readonly title: string;
  readonly body: string;
}

export interface KnowledgeDraftResult {
  readonly articles: readonly DraftedArticle[];
  /**
   * Модель упёрлась в потолок ответа, и хвост документа не разобран.
   * Администратору об этом говорится словами: молча оборванный
   * документ он принял бы за разобранный целиком.
   */
  readonly truncated: boolean;
}

export interface KnowledgeDrafter {
  draft(request: KnowledgeDraftRequest): Promise<KnowledgeDraftResult | null>;
}
