/**
 * Голые приветствия, на которые не нужен провайдер.
 *
 * Точное совпадение нормализованной строки, а не угадывание: «привет,
 * какой курс?» — это вопрос, и он уходит модели. Ошибиться здесь можно
 * только в одну сторону — не узнать приветствие, — и тогда на него
 * просто ответит модель.
 */
const GREETINGS = new Set([
  'привет',
  'приветик',
  'приветствую',
  'здравствуйте',
  'здравствуй',
  'добрый день',
  'день добрый',
  'добрый вечер',
  'доброе утро',
  'доброй ночи',
  'салют',
  'хай',
  'ку',
  'hi',
  'hello',
  'hey',
]);

/** Является ли сообщение целиком приветствием — и ничем больше. */
export function isGreetingOnly(text: string): boolean {
  const plain = text
    .toLowerCase()
    .replace(/ё/g, 'е')
    // Знаки, эмодзи и цифры не меняют приветствия: «Привет!!» и
    // «Привет 👋» — то же слово.
    .replace(/[^a-zа-я ]+/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();

  return plain !== '' && GREETINGS.has(plain);
}

