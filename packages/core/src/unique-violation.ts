/**
 * Нарушение уникальности, пришедшее от Postgres.
 *
 * Проверка «нет ли уже такого» и вставка — два действия, и между ними
 * успевает вклиниться второй запрос: мерчант повторил подачу, не
 * дождавшись ответа, две вкладки регистрации отправились разом. База
 * такую пару разнимает индексом, но наружу это уходит сырой ошибкой
 * драйвера — то есть пятисотым ответом там, где сервис знает, что
 * ответить.
 *
 * Опознаётся по коду `23505` и имени ограничения: по имени, а не по
 * тексту, потому что текст зависит от языка сервера, а имя мы задаём
 * сами в схеме.
 */
export function isUniqueViolation(error: unknown, constraint: string): boolean {
  if (typeof error !== 'object' || error === null) return false;
  const said = error as { code?: unknown; constraint_name?: unknown };
  return said.code === '23505' && said.constraint_name === constraint;
}
