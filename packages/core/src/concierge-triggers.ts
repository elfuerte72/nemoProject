/**
 * Слова, на которых консьерж замолкает и зовёт человека.
 *
 * Список срабатывает до вызова модели и минует её вовсе. Причина не в
 * экономии на запросе: провайдер отвечает рвано, и разговор, в котором
 * клиент пишет «отправил деньги, не пришли», не должен зависеть от
 * того, жива ли сейчас чужая сеть. Это самое дорогое сообщение из всех,
 * что приходят сервису, и решение по нему принимается здесь, а не там.
 *
 * Модель при этом зовёт человека и сама — полем в своём ответе. Одно
 * другого не заменяет: список ловит то, что нельзя пропустить, модель —
 * то, чего в списке не бывает («оплата второй день висит»).
 *
 * Ловится смысл, а не буква: у слова берётся основа, потому что клиент
 * пишет «обманули», «обманываете» и «обман» с равной охотой. Короткие
 * основы при этом ловятся только целым словом — «суд» сидит внутри
 * «судьбы» и «посуды», и список, ловящий их, уводит к менеджеру каждый
 * второй разговор.
 */

interface Trigger {
  /** Чем ловим. Уже приведено к нижнему регистру и без «ё». */
  readonly pattern: RegExp;
  /** Что сказать менеджеру: сводка отвечает «что случилось» до переписки. */
  readonly why: string;
}

/**
 * Граница слова по-русски.
 *
 * `\b` здесь бесполезен: он считает словом только латиницу с цифрами, и
 * «\bобман» не находит «обман» вовсе — перед кириллической буквой
 * границы для него не существует. Проверено падающим тестом, а не
 * рассуждением: список молчал на «вы меня обманули».
 */
const EDGE = String.raw`(?<!\p{L})`;

/** Основа: ловится начало слова, окончание любое. */
function stem(one: string): RegExp {
  return new RegExp(`${EDGE}${one}`, 'u');
}

/**
 * Целое слово. Для коротких основ единственно верное: «суд» сидит
 * внутри «судьбы» и «посуды», и основа увела бы к менеджеру разговор о
 * судьбе заявки.
 */
function whole(one: string): RegExp {
  return new RegExp(`${EDGE}${one}(?!\\p{L})`, 'u');
}

/**
 * Текст, приведённый к сравнимому виду. «Ё» заменяется: клиент пишет и
 * «дошёл», и «дошел», а список, различающий их, ловит половину.
 */
function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/g, 'е');
}

const TRIGGERS: readonly Trigger[] = [
  // Деньги, которых клиент не видит. Самое срочное из всего: пока идёт
  // разбирательство, у сервиса на руках чужой перевод.
  {
    pattern: /не при(шл|шел|дут|дет)|не поступил|не дошл|не дошел|не получил/,
    why: 'клиент говорит, что деньги не дошли',
  },
  { pattern: /где мо[ие][^.!?]{0,12}деньг/, why: 'клиент спрашивает, где его деньги' },

  // Обвинение и угроза. Отвечать на них автоматическим текстом — значит
  // подтверждать клиенту, что с ним никто не разговаривает.
  { pattern: stem('обман'), why: 'клиент обвиняет сервис в обмане' },
  { pattern: stem('мошенн'), why: 'клиент называет сервис мошенниками' },
  { pattern: whole('скам'), why: 'клиент называет сервис мошенниками' },
  { pattern: stem('вернит'), why: 'клиент требует вернуть деньги' },
  // Возвратами занимается строго менеджер (решение владельца): основа
  // «вернут» ловит «вернуть/вернут ли», но не «вернется» — про курс,
  // который вернется, спрашивают без задней мысли.
  { pattern: stem('возврат'), why: 'клиент спрашивает про возврат' },
  { pattern: stem('вернут'), why: 'клиент спрашивает про возврат денег' },
  { pattern: stem('жалоб'), why: 'клиент собирается жаловаться' },
  { pattern: stem('полиц'), why: 'клиент упоминает полицию' },
  { pattern: whole('суд[аеы]?'), why: 'клиент упоминает суд' },
  { pattern: stem('юрист'), why: 'клиент упоминает юриста' },
  { pattern: stem('адвокат'), why: 'клиент упоминает юриста' },
  { pattern: stem('претензи'), why: 'клиент предъявляет претензию' },
  { pattern: stem('заблокир'), why: 'клиент говорит о блокировке' },

  // Наличные — строго через менеджера: решение владельца, и промпт
  // дешёвой модели его не удержал (живая проба, 10 августа 2026).
  // Основа с границей слова: «безналичный» не задевается.
  { pattern: stem('наличн'), why: 'клиент спрашивает про наличные' },
  { pattern: stem('наличк'), why: 'клиент спрашивает про наличные' },

  // Прямая просьба. Отказать в ней — худшее, что может сделать первая
  // линия: клиент уже сказал, что разговаривать с ней не хочет.
  { pattern: stem('менеджер'), why: 'клиент просит менеджера' },
  { pattern: stem('оператор'), why: 'клиент просит оператора' },
  { pattern: stem('человек'), why: 'клиент просит живого человека' },
];

/**
 * Почему на это сообщение отвечает человек, а не консьерж. `null` —
 * обычный вопрос, консьерж отвечает сам.
 *
 * Возвращается причина, а не признак: она уходит менеджеру в сводке и
 * отвечает на вопрос «что случилось» до того, как он откроет переписку.
 */
export function escalationTrigger(text: string): string | null {
  const normalized = normalize(text);
  if (normalized.trim() === '') return null;

  return TRIGGERS.find((one) => one.pattern.test(normalized))?.why ?? null;
}
