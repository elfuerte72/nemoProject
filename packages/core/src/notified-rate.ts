import { sayRate, type Amount } from '@nemo/types';

/**
 * Числа, которыми сервис говорит с человеком: сумма и курс.
 *
 * Отдельным модулем, а не внутри `notifications.ts`, потому что те же
 * слова нужны письмам мерчанту (`merchant-mails.ts`), а письма
 * собираются из уведомлений: импорт в обе стороны замкнул бы их друг на
 * друга.
 */

/**
 * Число для человека: разряды через неразрывный пробел, дробная часть
 * через запятую и без хвоста нулей. «10000 USDT» в уведомлении читалось
 * как «1000» — ошибка в порядке величины там, где по числу решают.
 */
export function humanAmount(value: Amount): string {
  const [whole = '0', fraction = ''] = String(value).split('.');
  const grouped = whole.replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
  const tail = fraction.replace(/0+$/, '');
  return tail === '' ? grouped : `${grouped},${tail}`;
}

/**
 * Курс вместе с парой, к которой он относится.
 *
 * Пара едет с числом, а не рядом с ним: курс мелкой стороны хранится
 * частным (`roundRate`), а у направления со ступенчатой сеткой он и
 * вовсе выводится из выдачи делением, — и прочитать такое число без
 * кодов валют нечем. До 20 сентября 2026 в уведомлении стоял голый
 * `Amount`, и клиент, менявший рубли на монету, получал в чат
 * «0.011934598400763814» там, где менеджер видел «83,79 RUB за 1 USDT».
 *
 * Одним значением, а не тремя полями уведомления: курс без своей пары
 * собраться не должен вовсе — тип не даёт забыть её в новом переходе.
 */
export interface NotifiedRate {
  readonly rate: Amount;
  readonly fromCode: string;
  readonly toCode: string;
}

/**
 * Курс так, как его называют и клиенту, и мерчанту: крупной стороной
 * пары. Правило чтения — общее с панелью, Mini App и ботом (`sayRate` в
 * `@nemo/types`); здесь к нему добавлен только вид числа.
 */
export function sayNotifiedRate(rate: NotifiedRate): string {
  return sayRate(rate.rate, rate.fromCode, rate.toCode, humanAmount);
}
