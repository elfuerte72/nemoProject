/**
 * Сколько записей своей истории клиент получает за раз.
 *
 * Списки клиента — заявки на обмен, движения по баллам, заявки на вывод
 * и на карту — до сих пор отдавались целиком: истории было мало, и
 * потолок выглядел бы преждевременным. С отдельным разделом истории они
 * сходятся в одну ленту, и самый быстрый из них — движения по баллам:
 * начисление приходит на каждую сделку каждого приглашённого, и у
 * приведшего два десятка человек их набегает больше, чем собственных
 * заявок.
 *
 * Полусотни хватает на всё, ради чего в историю заходят, — а тянуть
 * следом сотни записей в Mini App поверх мобильной сети значит платить
 * за них временем открытия раздела.
 *
 * Потолок именно на списке, а не на ленте: потоков четыре, и общий
 * предел означал бы, что разговорчивые баллы вытесняют из ленты заявки
 * на обмен. Обрезанному концу ленты приложение говорит прямо — молча
 * показанный кусок читался бы как «это всё, что было».
 */
export const CLIENT_HISTORY_LIMIT = 50;
