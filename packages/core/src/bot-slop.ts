/**
 * Признаки машинного набора в текстах, которыми сервис говорит с
 * клиентом.
 *
 * Правило, а не вкус: длинное тире по-русски законно, и запрещать его
 * нельзя. Машинным текст делает не знак, а его ритм — связка «X — Y»,
 * повторённая в одном предложении или выстроенная столбцом. Человек так
 * не пишет: он меняет строй фразы, а генератор держит один и тот же.
 *
 * Пороги названы у самих правил ниже, и они разные: в предложении
 * хватает второй связки, а столбцом — третьей строки. Пара строк это
 * ещё не столбец: ею набирают курс покупки и продажи.
 *
 * Здесь, а не в ревью: тексты правятся раз в полгода, и к этому времени
 * замечание из прошлого ревью помнит только тот, кто его делал. Здесь,
 * а не в чужом линтере прозы: готовые наборы признаков собраны по
 * английскому, где длинное тире само по себе редкость, — на русском они
 * помечают каждый абзац.
 *
 * Ловится опечатка стиля, а не авторство: текст, прошедший проверку, всё
 * ещё может быть написан машиной. Обратное важнее — помеченный ею
 * читается машинным даже когда написан руками.
 */

/** Длинное тире. Короткое (`–`) и дефис в текстах не в этой роли. */
const DASH = '—';

/**
 * Сколько связок в предложении — уже ритм.
 *
 * Одна законна и часто единственно верна: «Курс виден сразу — по нему и
 * обменяем». Вторая в том же предложении означает, что строй фразы не
 * менялся, — а именно этого человек и не делает.
 */
const SENTENCE_LIMIT = 2;

/**
 * Сколько строк подряд со связкой уже читаются столбцом.
 *
 * Две — это пара, какой набирают курс покупки и продажи. Три подряд уже
 * ритм, и глаз ловит его раньше слов.
 */
const RUN_LIMIT = 3;

/** Обрезок строки для жалобы: целиком она в отчёт теста не помещается. */
function short(line: string): string {
  const clean = line.replace(/<[^>]+>/g, '').trim();
  return clean.length > 60 ? `${clean.slice(0, 57)}…` : clean;
}

function countDashes(text: string): number {
  return [...text].filter((char) => char === DASH).length;
}

/**
 * Предложения строки. Разбиение грубое и намеренно такое: сокращения
 * вроде «т. д.» в текстах бота не встречаются, а лишнее разбиение здесь
 * только ослабляет проверку — оно не выдумывает жалобу, а теряет её.
 */
function sentences(line: string): readonly string[] {
  return line.split(/(?<=[.!?…])\s+/u).filter((one) => one.trim() !== '');
}

/** Самая длинная череда идущих подряд строк со связкой. */
function longestRun(lines: readonly string[]): number {
  let longest = 0;
  let current = 0;
  for (const line of lines) {
    current = line.includes(DASH) ? current + 1 : 0;
    longest = Math.max(longest, current);
  }
  return longest;
}

/**
 * Чем текст выдаёт машинный набор. Пустой список — текст чист.
 *
 * Жалоба называет место и причину: «исправьте» без «где» приводит к
 * тому, что правят наугад весь абзац.
 */
export function slopComplaints(text: string): readonly string[] {
  const complaints: string[] = [];

  // Двойной дефис руками не набирают: он остаётся там, где длинное тире
  // подставлял не человек.
  if (text.includes('--')) {
    complaints.push('двойной дефис «--»: руками его не набирают');
  }

  const lines = text.split('\n');

  for (const line of lines) {
    for (const sentence of sentences(line)) {
      const dashes = countDashes(sentence);
      if (dashes >= SENTENCE_LIMIT) {
        complaints.push(
          `${dashes} длинных тире в одном предложении: «${short(sentence)}»`,
        );
      }
    }
  }

  const run = longestRun(lines);
  if (run >= RUN_LIMIT) {
    complaints.push(
      `${run} строки подряд с длинным тире: столбец одинаковых связок читается набранным`,
    );
  }

  return complaints;
}
