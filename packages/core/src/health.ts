import { sql } from 'drizzle-orm';
import type { CoreConfig } from './context.js';

/**
 * Пульс базы для маршрута `/api/health`.
 *
 * Самый дешёвый запрос, какой есть: `select 1` не читает ни одной
 * таблицы, но проходит весь путь целиком — соединение, аутентификацию,
 * ответ. Ровно это снаружи и хотят знать: жив ли контейнер и видит ли
 * он базу. О содержимом базы операция не сообщает ничего — маршрут,
 * который её зовёт, открыт из интернета без подписи.
 *
 * Срока ожидания здесь нет намеренно: он свойство ответа, а не
 * запроса, и живёт в обвязке маршрута, где решают, что считать
 * «слишком долго».
 */
export async function pingDatabase(ctx: CoreConfig): Promise<void> {
  await ctx.db.execute(sql`select 1`);
}
