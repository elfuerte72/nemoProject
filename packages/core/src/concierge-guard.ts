import { slopComplaints } from './bot-slop.js';

/**
 * Застава перед ответом консьержа.
 *
 * Модель дешёвая, разговор идёт про деньги, и единственное, чего нельзя
 * допустить, — названное ею число, которого сервис не называл. Курс,
 * сумма и срок, взятые из воздуха, читаются клиентом как обещание
 * сервиса; спорить он потом будет со скриншотом, и будет прав.
 *
 * Отсюда правило, грубое намеренно: в ответе не бывает числа, которого
 * нет ни в справке, которую собрало ядро, ни в словах самого клиента.
 * Модели об этом сказано прямо, а деньги ей велено называть цифрами из
 * справки — но держится правило здесь, а не на её послушании. Грубость — цена:
 * законный ответ иногда отвергается, и тогда идёт повтор, а за ним
 * запасной текст и человек. Обратная ошибка стоит дороже.
 *
 * Ритм проверяется тем же `bot-slop`, что и рукописные тексты: сервис
 * говорит одним голосом, и то, что помечено машинным у него в коде,
 * машинно и в ответе модели.
 */

/**
 * Сколько текста уходит клиенту.
 *
 * Семьсот знаков — это пять-шесть строк в чате, то есть ответ, который
 * дочитывают. Всё, что длиннее, в поддержке обменника означает пересказ
 * справки вместо ответа на вопрос.
 */
export const MAX_REPLY_LENGTH = 700;

export interface ReplyGuardInput {
  readonly reply: string;
  /**
   * Тексты, чьи числа называть можно: справка, собранная ядром, и то,
   * что написал сам клиент. Клиент назвал свою сумму — повторить её в
   * ответе не выдумка, а признак того, что его прочитали.
   */
  readonly sources: readonly string[];
}

/**
 * Число в тексте: разряды бывают разбиты пробелом, дробная часть —
 * запятой или точкой. Знак после числа в захват не идёт: точка в конце
 * предложения к числу не относится.
 */
const NUMBER = /\d+(?:[\s ]\d{3})*(?:[.,]\d+)?/g;

/**
 * Число, приведённое к сравнимому виду. Разделитель разрядов, вид
 * дробной запятой и хвост нулей — оформление: «81,25», «81.25» и
 * «81,2500» это одно число, и отличать их значило бы ловить не выдумку,
 * а вёрстку.
 *
 * Хвост нулей важен не в теории: справка печатает курс так, как он
 * лежит в базе, а модель незначащие нули отбрасывает — и законный ответ
 * уходил человеку как выдуманный.
 */
function normalize(one: string): string {
  const plain = one.replace(/[\s ]/g, '').replace(',', '.');
  return plain.includes('.') ? plain.replace(/0+$/, '').replace(/\.$/, '') : plain;
}

function numbersIn(text: string): readonly string[] {
  return (text.match(NUMBER) ?? []).map(normalize);
}

/**
 * Служебная кухня, которой клиент не видел и видеть не должен.
 *
 * Модель получает справку, правила разговора и сигнальное слово — и
 * пересказывает их клиенту как часть ответа: «в справке указаны только
 * направления». Клиент узнаёт, что у сервиса есть какая-то справка, и
 * не узнаёт ничего по существу вопроса. Сюда же попадает и само
 * сигнальное слово: распознанное, оно уходит человеку, а не
 * распознанное — уезжало клиенту хвостом ответа.
 */
const BACKSTAGE =
  /справк[аеиуой]|в справке|инструкц|база знаний|базе знаний|предоставленн|как (ии|ai|бот)\b|языковая модель|искусственн\w* интеллект|(^|\n)\s*(МЕНЕДЖЕР|ОФФТОП|ПОДСКАЗКА[^\n]*)\s*($|\n)/iu;

/**
 * Разметка. В переписке её не набирают: список из трёх пунктов, звёздочки
 * жирного и заголовок — вид документа, а не ответа человека в чате.
 * Абзац разметкой не считается: им говорят и люди.
 */
const MARKUP = /(^|\n)\s*([-*•]\s|#{1,6}\s|\d+[.)]\s)|\*\*/u;

/** Смайлики: сервис ими не говорит ни в одном своём тексте. */
const PICTURES = /\p{Extended_Pictographic}/u;

/**
 * Помощник, назвавшийся человеком.
 *
 * Клиент, решивший, что говорит с сотрудником, поверит и обещанию,
 * которого сотрудник не давал, — а спорить потом будет со скриншотом,
 * как и в случае с выдуманным курсом. Ловится только прямое «я
 * сотрудник»: «позову менеджера» — честная фраза, и запрещать слово
 * значило бы запретить единственный способ назвать, кто ответит дальше.
 */
// Граница слова записана оглядкой на букву, а не `\b`: тот считает
// границей всякий переход между латиницей и прочим, и на кириллице
// срабатывает где попало.
const IMPERSONATION =
  /(?<!\p{L})я\s+(—\s+)?(сотрудник|менеджер|оператор|специалист|консультант)/iu;

/**
 * Обещание срока.
 *
 * Числа проверяются справкой, но срок модель обещает и словами: «пара
 * минут» проходит мимо проверки чисел, оставаясь тем же обещанием, что
 * и «две минуты». Обещанный срок стоит сервису столько же, сколько
 * выдуманный курс: клиент ждёт по нему.
 *
 * Ловится сочетание количества с единицей времени, и жалоба ставится
 * только когда в справке сроков нет вовсе. Есть — значит их назвал
 * сервис, и повторить их можно: то же правило, что у чисел, только
 * записанное словами.
 *
 * Единица берётся с границей слова: «час» сидит внутри «сейчас», «дни» —
 * внутри «сотрудников», и без границы одно такое слово в справке молча
 * разоружало бы весь запрет, а в ответе — рождало ложную жалобу.
 * «Полчаса» и «полдня» стоят отдельной веткой: количество в них вросло
 * в само слово.
 */
const DURATION =
  /(\d+|пар[ауы]|несколько|одн[уого]|дв[уаех]|тр[иёе]|четыр|пят|десят|минут)\s*[а-яё]*\s*(?<!\p{L})(минут|час|сут|дн[еяёи]|недел)|(?<!\p{L})пол[у]?(минут|час|сут|дн[еяёи]|недел)/iu;

/** Единица времени в справке: по ней видно, называл ли сервис сроки. */
export const TIME_UNIT = /(?<!\p{L})(пол[у]?)?(минут|час|сут|дн[еяёи]|недел)/iu;

/**
 * Сумма прописью.
 *
 * Застава чисел видит только цифры, и «пятьдесят тысяч рублей» проходит
 * мимо неё с тем же весом обещания, что и «50000». Модели велено
 * называть деньги цифрами из справки; здесь это правило держится кодом.
 * Ловится числительное вплотную к валюте: суммы справка печатает
 * цифрами, и словесной суммы в честном ответе не бывает.
 *
 * Числительные перечислены формами, а не основами: основа «тр» ловила
 * бы «требуются рубли», а «сем» — «семью». Валюта обязана стоять сразу
 * за числительным — «тысячи вопросов о рублях» суммой не является.
 */
const NUMERAL_WORD = [
  'дв(?:а|е|ух|умя|ести)',
  'двадцат\\p{L}*',
  'три',
  'тр(?:ё|е)х\\p{L}*',
  'тридцат\\p{L}*',
  'триста',
  'четыре',
  'четыр(?:ё|е)х\\p{L}*',
  'четырест\\p{L}*',
  'пят(?:ь|и|ью)',
  'пятьдесят',
  'пятидесяти',
  'пят(?:ь|и)сот',
  'шест(?:ь|и|ью)',
  'шестьдесят',
  'шестидесяти',
  'шест(?:ь|и)сот',
  'сем(?:ь|и|ью)',
  'семьдесят',
  'семидесяти',
  'сем(?:ь|и)сот',
  'восем(?:ь|ью)',
  'восьми',
  'восемьдесят',
  'восьмидесяти',
  'восем(?:ь|и)сот',
  'восьмисот',
  'девят(?:ь|и|ью)',
  'девяност\\p{L}*',
  'девят(?:ь|и)сот',
  'десят(?:ь|и|ью|к\\p{L}*)',
  'сорок\\p{L}*',
  'сто',
  'сотн\\p{L}*',
  'тысяч\\p{L}*',
  'миллион\\p{L}*',
  'полтор\\p{L}*',
].join('|');

const WORDY_AMOUNT = new RegExp(
  String.raw`(?<!\p{L})(?:${NUMERAL_WORD})\s+(?:рубл|доллар|бат|юан|лир|рупи|ранд|евро|usdt)`,
  'iu',
);

/**
 * Чем ответ модели не годится для отправки. Пустой список — годится.
 *
 * Жалоба называет причину: она уходит обратно в модель на повтор, и
 * «перепишите» без «что именно не так» даёт второй такой же ответ.
 */
export function replyComplaints(input: ReplyGuardInput): readonly string[] {
  const reply = input.reply.trim();
  // Пустой ответ проверять дальше нечем, а жалоб он собрал бы сразу
  // несколько — и повтор ушёл бы исправлять не то.
  if (reply === '') {
    return ['ответ пуст: клиенту нечего читать'];
  }

  const complaints: string[] = [];

  if (reply.length > MAX_REPLY_LENGTH) {
    complaints.push(
      `ответ длиннее ${MAX_REPLY_LENGTH} знаков: в чате его дочитывают до середины`,
    );
  }

  const allowed = new Set(input.sources.flatMap(numbersIn));
  for (const number of numbersIn(reply)) {
    if (!allowed.has(number)) {
      complaints.push(
        `число «${number}» сервис не называл: в ответе бывают только числа из справки`,
      );
    }
  }

  const backstage = BACKSTAGE.exec(reply);
  if (backstage !== null) {
    complaints.push(
      `«${backstage[0].trim()}»: клиент не знает ни про справку, ни про правила ответа — отвечайте по существу`,
    );
  }

  const impersonation = IMPERSONATION.exec(reply);
  if (impersonation !== null) {
    complaints.push(
      `«${impersonation[0].trim()}»: помощник называет себя помощником, а не человеком`,
    );
  }

  const wordyAmount = WORDY_AMOUNT.exec(reply);
  if (wordyAmount !== null) {
    complaints.push(
      `«${wordyAmount[0].trim()}»: сумма словами обходит проверку чисел — деньги называются цифрами и только из справки`,
    );
  }

  const duration = DURATION.exec(reply);
  if (duration !== null && !input.sources.some((one) => TIME_UNIT.test(one))) {
    complaints.push(
      `«${duration[0].trim()}»: срок сервис не называл, а обещание срока ждут так же, как курс`,
    );
  }

  if (MARKUP.test(reply)) {
    complaints.push('разметка списком или заголовком: в переписке пишут фразами');
  }

  if (PICTURES.test(reply)) {
    complaints.push('смайлик: сервис ими не говорит');
  }

  complaints.push(...slopComplaints(reply));

  return complaints;
}
