import { slopComplaints } from './bot-slop.js';

/**
 * Застава перед ответом консьержа.
 *
 * Модель дешёвая, разговор идёт про деньги, и единственное, чего нельзя
 * допустить, — названное ею число, которого сервис не называл. Курс,
 * сумма и срок, взятые из воздуха, читаются клиентом как обещание
 * сервиса; спорить он потом будет со скриншотом, и будет прав.
 *
 * Отсюда правило, грубое намеренно: в ответе не бывает числа, которого
 * нет ни в справке, которую собрало ядро, ни в словах самого клиента.
 * Модели об этом сказано прямо, а количества ей велено писать словами —
 * но держится правило здесь, а не на её послушании. Грубость — цена:
 * законный ответ иногда отвергается, и тогда идёт повтор, а за ним
 * запасной текст и человек. Обратная ошибка стоит дороже.
 *
 * Ритм проверяется тем же `bot-slop`, что и рукописные тексты: сервис
 * говорит одним голосом, и то, что помечено машинным у него в коде,
 * машинно и в ответе модели.
 */

/**
 * Сколько текста уходит клиенту.
 *
 * Семьсот знаков — это пять-шесть строк в чате, то есть ответ, который
 * дочитывают. Всё, что длиннее, в поддержке обменника означает пересказ
 * справки вместо ответа на вопрос.
 */
export const MAX_REPLY_LENGTH = 700;

export interface ReplyGuardInput {
  readonly reply: string;
  /**
   * Тексты, чьи числа называть можно: справка, собранная ядром, и то,
   * что написал сам клиент. Клиент назвал свою сумму — повторить её в
   * ответе не выдумка, а признак того, что его прочитали.
   */
  readonly sources: readonly string[];
}

/**
 * Число в тексте: разряды бывают разбиты пробелом, дробная часть —
 * запятой или точкой. Знак после числа в захват не идёт: точка в конце
 * предложения к числу не относится.
 */
const NUMBER = /\d+(?:[\s ]\d{3})*(?:[.,]\d+)?/g;

/**
 * Число, приведённое к сравнимому виду. Разделитель разрядов и вид
 * дробной запятой — оформление: «81,25» и «81.25» это одно число, и
 * отличать их значило бы ловить не выдумку, а вёрстку.
 */
function normalize(one: string): string {
  return one.replace(/[\s ]/g, '').replace(',', '.');
}

function numbersIn(text: string): readonly string[] {
  return (text.match(NUMBER) ?? []).map(normalize);
}

/**
 * Чем ответ модели не годится для отправки. Пустой список — годится.
 *
 * Жалоба называет причину: она уходит обратно в модель на повтор, и
 * «перепишите» без «что именно не так» даёт второй такой же ответ.
 */
export function replyComplaints(input: ReplyGuardInput): readonly string[] {
  const reply = input.reply.trim();
  // Пустой ответ проверять дальше нечем, а жалоб он собрал бы сразу
  // несколько — и повтор ушёл бы исправлять не то.
  if (reply === '') {
    return ['ответ пуст: клиенту нечего читать'];
  }

  const complaints: string[] = [];

  if (reply.length > MAX_REPLY_LENGTH) {
    complaints.push(
      `ответ длиннее ${MAX_REPLY_LENGTH} знаков: в чате его дочитывают до середины`,
    );
  }

  const allowed = new Set(input.sources.flatMap(numbersIn));
  for (const number of numbersIn(reply)) {
    if (!allowed.has(number)) {
      complaints.push(
        `число «${number}» сервис не называл: в ответе бывают только числа из справки`,
      );
    }
  }

  complaints.push(...slopComplaints(reply));

  return complaints;
}
