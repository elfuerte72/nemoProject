/**
 * Банки, в которые клиент просит перевод чаще прочих, — ярлыками к полю
 * «Банк».
 *
 * Подсказка, а не список: набрать своё по-прежнему можно. Закрытым его
 * не сделать — тайских банков не шесть, а полсотни, и клиент с GSB или
 * BAAC (счёт у них в двенадцать цифр, `looksLikeThaiAccount` про это
 * знает) упёрся бы в список, из которого нечего выбрать. Ярлык здесь
 * экономит набор латиницы на телефоне, а не решает, куда сервис умеет
 * отправлять: это решает справочник направлений.
 *
 * Ключ — валюта записи, а не род реквизита: поле «Банк» стоит у рублёвых
 * карты и телефона и у тайского счёта, и банк в нём зависит от того, в
 * какой валюте счёт, а не от того, чем он назван.
 *
 * Одно место на Mini App, кабинет мерчанта и счета сервиса в панели:
 * второй список тайских банков разошёлся бы с первым молча — клиент
 * набрал бы «Krungthai», менеджер завёл бы «Krung Thai», и на сверке
 * это два разных банка.
 *
 * Написан ярлык так, как банк называет себя сам, и подставляется он
 * ровно тем, что на нём написано: чип, обещающий «SCB», а кладущий в
 * поле «Siam Commercial Bank», читается как ошибка формы.
 */
const BANKS: Record<string, readonly string[]> = {
  /*
   * Тайские — из ТЗ владельца на перевод рублей в баты (9 сентября
   * 2026). В письме их семь, но Krung Thai Bank и Krungthai Bank —
   * один банк, и ярлыка ему полагается один.
   */
  THB: ['Bangkok Bank', 'Kasikornbank', 'Krungthai Bank', 'SCB', 'Krungsri', 'TTB'],
  RUB: ['Сбербанк', 'Т-Банк', 'Альфа-Банк', 'ВТБ', 'Райффайзенбанк', 'Озон Банк'],
};

/**
 * Ярлыки к полю «Банк» для этой валюты. Пусто — у валюты банков не
 * бывает (USDT приходит на кошелёк) или подсказок для неё не заведено;
 * пустой список экран не показывает вовсе.
 */
export function bankSuggestionsFor(currencyCode: string): readonly string[] {
  return BANKS[currencyCode.toUpperCase()] ?? [];
}
