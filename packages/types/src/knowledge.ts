/**
 * База знаний помощника: правило одноимённости статей.
 *
 * Одно название — одна статья. Регистр и пробелы по краям не делают
 * «График работы» и «график работы» двумя темами: документ присылают
 * обновлённым, и «Оплата» обязана заменить «Оплату», а не встать рядом.
 *
 * Здесь, а не в ядре, по той же причине, что и правдоподобие реквизита:
 * правило повторяет экран — он говорит «заменит статью такую-то» до
 * записи, — и повторять его обязан тем же кодом, что и запись, иначе
 * обещал бы одно, а делал другое.
 */
export function normalizeKnowledgeTitle(title: string): string {
  return title.trim().replace(/\s+/g, ' ').toLowerCase();
}
