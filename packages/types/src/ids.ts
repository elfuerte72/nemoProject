/**
 * Идентификаторы, пришедшие строкой: из адреса, из поля поиска, из
 * пути запроса к API.
 *
 * Заявка, мерчант, запись реквизита, ключ — UUID; клиент — Telegram ID,
 * положительное целое в пределах `bigint` Postgres. Строку не того вида
 * база не ищет, а отвергает ошибкой, и отказ этот доходил до человека
 * страницей аварии, а до мерчанта — `500 internal` вместо обещанного
 * договором `404`. Поэтому вид проверяется до запроса, а строка не того
 * вида значит то же, что и несуществующий номер: такого нет.
 */

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * UUID в каноническом виде — с дефисами, в любом регистре. Иные виды,
 * которые Postgres тоже разбирает (без дефисов, в фигурных скобках),
 * сервис не выдаёт нигде, и в адресе они означают опечатку.
 */
export function isUuid(raw: string): boolean {
  return UUID.test(raw);
}

/** Верх `bigint` в Postgres: число больше — не идентификатор, а опечатка. */
export const MAX_TELEGRAM_USER_ID = 9_223_372_036_854_775_807n;

/**
 * Telegram ID из строки — или пусто, если строка им быть не может.
 * Только цифры, без знака и пробелов: `BigInt(' 5')` число даёт, но
 * такой адрес набран руками, а не взят из ссылки сервиса.
 */
export function parseTelegramUserId(raw: string): bigint | null {
  if (!/^\d{1,19}$/.test(raw)) return null;
  const value = BigInt(raw);
  return value > 0n && value <= MAX_TELEGRAM_USER_ID ? value : null;
}
