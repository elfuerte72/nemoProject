import { describe, expect, it } from 'vitest';
import { readRate } from './rate.js';
import * as Money from './money.js';

/**
 * Как читается курс — одним правилом на оба приложения.
 *
 * Клиент видит «81 ₽ за 1 USDT», менеджер сверяет с тем же числом, и
 * бот повторяет его в чате. Три копии правила разошлись бы молча: курс
 * читается глазами и не проверяется ничем, кроме внимательности.
 */

const rate = (value: string) => Money.toAmount(value);

describe('сторона пары', () => {
  it('крупная сторона остаётся как есть', () => {
    expect(readRate(rate('82'), 'USDT', 'RUB')).toEqual({
      value: '82',
      perCode: 'RUB',
      unitCode: 'USDT',
    });
  });

  /*
   * «1 RUB ≈ 0,0122 USDT» формально то же самое, но числом в сотых
   * долях никто не пользуется и с курсом соседнего обменника его не
   * сравнить, не перевернув в уме.
   */
  it('мелкая переворачивается вместе с подписью', () => {
    expect(readRate(rate('0.012195121951219512'), 'RUB', 'USDT')).toEqual({
      value: '82',
      perCode: 'RUB',
      unitCode: 'USDT',
    });
  });
});

describe('округление', () => {
  it('снимает хвост, оставшийся от переворота', () => {
    // Обратное деление даёт 81,999…, и вниз это дало бы 81,99.
    expect(readRate(rate('0.0121951219512195'), 'RUB', 'USDT').value).toBe('82');
  });

  /*
   * Курс называется до сотых — и до сотых же считается в ядре. Целого
   * больше нет: до 28 августа 2026 курс округлялся до рубля, и владелец
   * прочёл это как ошибку — «Rapira минус два процента это 83,79, а в
   * приложении 83». Сотые отбрасываются вниз, а не к ближайшему: 82,666,
   * показанные как 82,67, обещали бы клиенту копейку, которой сделка не
   * даёт.
   */
  it('прямой курс отбрасывает вниз до сотых', () => {
    expect(readRate(rate('82.6612'), 'USDT', 'RUB').value).toBe('82.66');
    expect(readRate(rate('82.666'), 'USDT', 'RUB').value).toBe('82.66');
    expect(readRate(rate('83.79'), 'USDT', 'RUB').value).toBe('83.79');
  });

  it('целое и десятые не удлиняет нулями', () => {
    expect(readRate(rate('82'), 'USDT', 'RUB').value).toBe('82');
    expect(readRate(rate('82.4'), 'USDT', 'RUB').value).toBe('82.4');
  });

  /*
   * Дефект, ради которого правило и собрано в одном месте: у пары
   * USDT → EUR курс 0,847, перевёрнутый и округлённый к целому, читался
   * как «1 USDT за 1 EUR». За евро при этом просят 1,18 монеты, и
   * округление съедало восемнадцать процентов — впятеро больше наценки.
   */
  it('перевёрнутый курс поднимает вверх до сотых', () => {
    expect(readRate(rate('0.847'), 'USDT', 'EUR')).toEqual({
      // Перевёрнутый курс — «сколько отдать за единицу», и лишняя сотая
      // здесь в пользу сервиса: обещать меньше, чем возьмёшь, нельзя.
      value: '1.19',
      perCode: 'USDT',
      unitCode: 'EUR',
    });
  });

  it('и с другой стороны тоже', () => {
    // Прямой курс — «сколько получить», и сотая отбрасывается вниз.
    expect(readRate(rate('1.1806'), 'EUR', 'USDT').value).toBe('1.18');
  });

  /*
   * Покупка USDT за рубли у владельца: Rapira 85,5, наценка два
   * процента с отдаваемой суммы — 87,2449 рубля за монету. Хранится
   * частным, читается крупной стороной, и вверх это 87,25.
   */
  it('покупку монеты называет рублями за монету, до сотых вверх', () => {
    expect(readRate(rate('0.011461988304093567'), 'RUB', 'USDT')).toEqual({
      value: '87.25',
      perCode: 'RUB',
      unitCode: 'USDT',
    });
  });
});

/*
 * До 28 августа 2026 целое допускалось, пока сдвиг не больше наценки, и
 * граница эта была правилом про деньги. Теперь границы нет: шаг —
 * сотая при любом курсе, и на восьмидесяти рублях за монету, и около
 * единицы. Бат от этого перестаёт мигать между «32» и «32,67» — прежде
 * он стоял ровно на границе.
 */
describe('шаг один на любой курс', () => {
  it('около единицы — та же сотая, что и на восьмидесяти', () => {
    expect(readRate(rate('1.019'), 'USDT', 'EUR').value).toBe('1.01');
    expect(readRate(rate('1.03'), 'USDT', 'EUR').value).toBe('1.03');
  });

  it('перевёрнутый — так же, вверх', () => {
    // 1/0,505 = 1,9802: до двух один процент, но целого больше нет.
    expect(readRate(rate('0.505'), 'USDT', 'EUR').value).toBe('1.99');
    // 1/0,6 = 1,666…: вверх до сотых.
    expect(readRate(rate('0.6'), 'USDT', 'EUR').value).toBe('1.67');
  });

  it('бат не мигает: 32,67 остаётся 32,67', () => {
    expect(readRate(rate('32.67'), 'USDT', 'THB').value).toBe('32.67');
    expect(readRate(rate('32.675'), 'USDT', 'THB').value).toBe('32.67');
  });
});

describe('края', () => {
  it('нулевой курс из старой заявки не роняет экран делением', () => {
    expect(readRate(rate('0'), 'RUB', 'USDT')).toEqual({
      value: '0',
      perCode: 'USDT',
      unitCode: 'RUB',
    });
  });

  it('отрицательный оставляет как есть', () => {
    expect(readRate(rate('-5'), 'RUB', 'USDT').value).toBe('-5');
  });
});
