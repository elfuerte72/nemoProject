import { describe, expect, it } from 'vitest';
import { readRate } from './rate.js';
import * as Money from './money.js';

/**
 * Как читается курс — одним правилом на оба приложения.
 *
 * Клиент видит «81 ₽ за 1 USDT», менеджер сверяет с тем же числом, и
 * бот повторяет его в чате. Три копии правила разошлись бы молча: курс
 * читается глазами и не проверяется ничем, кроме внимательности.
 */

const rate = (value: string) => Money.toAmount(value);

describe('сторона пары', () => {
  it('крупная сторона остаётся как есть', () => {
    expect(readRate(rate('82'), 'USDT', 'RUB')).toEqual({
      value: '82',
      perCode: 'RUB',
      unitCode: 'USDT',
    });
  });

  /*
   * «1 RUB ≈ 0,0122 USDT» формально то же самое, но числом в сотых
   * долях никто не пользуется и с курсом соседнего обменника его не
   * сравнить, не перевернув в уме.
   */
  it('мелкая переворачивается вместе с подписью', () => {
    expect(readRate(rate('0.012195121951219512'), 'RUB', 'USDT')).toEqual({
      value: '82',
      perCode: 'RUB',
      unitCode: 'USDT',
    });
  });
});

describe('округление', () => {
  it('снимает хвост, оставшийся от переворота', () => {
    // Обратное деление даёт 81,999…, и вниз это дало бы 81.
    expect(readRate(rate('0.0121951219512195'), 'RUB', 'USDT').value).toBe('82');
  });

  /*
   * Дробный курс приходит из заявок, поданных до того, как ядро стало
   * округлять. Отбрасывается вниз, а не к ближайшему: 82,66,
   * показанные как 83, обещали бы клиенту рубль, которого сделка не
   * даёт, — а показанные как 82, обещают меньше, чем он получит.
   */
  it('дробный курс из прежних заявок отбрасывает вниз', () => {
    expect(readRate(rate('82.6612'), 'USDT', 'RUB').value).toBe('82');
    expect(readRate(rate('82.4'), 'USDT', 'RUB').value).toBe('82');
  });

  /*
   * Дефект, ради которого правило и собрано в одном месте: у пары
   * USDT → EUR курс 0,847, перевёрнутый и округлённый к целому, читался
   * как «1 USDT за 1 EUR». За евро при этом просят 1,18 монеты, и
   * округление съедает восемнадцать процентов — впятеро больше наценки.
   */
  it('курс около единицы остаётся дробным', () => {
    expect(readRate(rate('0.847'), 'USDT', 'EUR')).toEqual({
      // Перевёрнутый курс — «сколько отдать за единицу», и лишняя сотая
      // здесь в пользу сервиса: обещать меньше, чем возьмёшь, нельзя.
      value: '1.19',
      perCode: 'USDT',
      unitCode: 'EUR',
    });
  });

  it('и с другой стороны тоже', () => {
    // Прямой курс — «сколько получить», и сотая отбрасывается вниз.
    expect(readRate(rate('1.1806'), 'EUR', 'USDT').value).toBe('1.18');
  });
});

/*
 * Граница округления — то же правило, по которому округляет сам курс
 * ядро: целое допускается, пока сдвиг не больше наценки. Проверяется
 * она с обеих сторон и в обе стороны, потому что это правило про
 * деньги: разрешив на процент больше, сервис отдаёт этот процент.
 */
describe('граница округления', () => {
  it('прямой курс округляет, пока сдвиг укладывается в наценку', () => {
    // 1,019: до целого не хватает 1,9% — меньше двух, и целое проходит.
    expect(readRate(rate('1.019'), 'USDT', 'EUR').value).toBe('1');
  });

  it('и оставляет дробным, когда не укладывается', () => {
    // 1,03: до целого 2,9% — больше наценки, и целое отняло бы её всю.
    expect(readRate(rate('1.03'), 'USDT', 'EUR').value).toBe('1.03');
  });

  it('перевёрнутый — так же, но округляя вверх', () => {
    // 1/0,505 = 1,98: до двух 1%, и клиент отдаёт на копейку больше.
    expect(readRate(rate('0.505'), 'USDT', 'EUR').value).toBe('2');
  });

  it('и вверх же оставляет сотые, когда целое слишком далеко', () => {
    // 1/0,6 = 1,666…: до двух двадцать процентов, целое врало бы вчетверо.
    expect(readRate(rate('0.6'), 'USDT', 'EUR').value).toBe('1.67');
  });
});

describe('края', () => {
  it('нулевой курс из старой заявки не роняет экран делением', () => {
    expect(readRate(rate('0'), 'RUB', 'USDT')).toEqual({
      value: '0',
      perCode: 'USDT',
      unitCode: 'RUB',
    });
  });

  it('отрицательный оставляет как есть', () => {
    expect(readRate(rate('-5'), 'RUB', 'USDT').value).toBe('-5');
  });
});
