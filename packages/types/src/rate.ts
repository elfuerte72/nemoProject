import * as Money from './money.js';
import type { Amount } from './money.js';

/**
 * Как читается курс — одним правилом на весь сервис.
 *
 * Клиент видит его на экране обмена, в сводке перед подачей и в
 * истории; менеджер сверяет с ним то же число в карточке заявки; бот
 * повторяет его в чате. Правило, размноженное по этим местам, разошлось
 * бы молча: курс читают глазами, и «не тот» от «того» отличается только
 * тем, что кто-то заметит.
 *
 * Здесь живёт домен: какая сторона пары называется и каким числом.
 * Вид самого числа — дело каждого приложения: клиент обрезает дробный
 * хвост на восьмом знаке, панель показывает все значащие, и общим
 * оказался бы весь их набор форматов ради одной функции.
 */

/**
 * Насколько округление вправе сдвинуть курс — то же правило, по
 * которому округляет сам курс ядро (`roundRate`).
 *
 * Двести базисных пунктов — два процента: столько же, сколько нынешняя
 * наценка сервиса. Округление, превышающее её, увело бы сделку в минус.
 */
export const MAX_ROUNDING_BPS = 200;

/** Знаков у курса, которому целое не подходит: столько же, сколько на табло. */
const NEAR_UNIT_DIGITS = 2;

export interface RateReading {
  /** Число, которое называют. */
  readonly value: Amount;
  /** Валюта этого числа. */
  readonly perCode: string;
  /** Валюта единицы, за которую его дают: «… за 1 unitCode». */
  readonly unitCode: string;
}

/**
 * Курс словами: число, его валюта и единица, за которую его дают.
 *
 * Здесь же, а не в каждом приложении: сама строка «81 RUB за 1 USDT» —
 * такая же часть правила, как и то, какая сторона называется. Набранная
 * дважды, она разойдётся первой же правкой, и менеджер с клиентом
 * прочтут один курс по-разному — ровно то, ради чего правило и сведено
 * в одно место.
 *
 * Вид числа приложение задаёт своим `digits`: клиент обрезает дробный
 * хвост на восьмом знаке, панель показывает все значащие — и общими им
 * быть незачем.
 */
export function sayRate(
  rate: Amount,
  fromCode: string,
  toCode: string,
  digits: (value: Amount) => string,
): string {
  const reading = readRate(rate, fromCode, toCode);
  return `${digits(reading.value)} ${reading.perCode} за 1 ${reading.unitCode}`;
}

/**
 * Убрать у числа хвост, оставшийся от деления.
 *
 * Курс мельче единицы хранится как частное, и обратное деление
 * возвращает не 82, а 81,999999999999998. Девяти знаков хватает:
 * настоящая дробная часть курса крупнее их на порядки, а шум деления
 * мельче.
 *
 * Отсюда же им пользуется ядро, округляя сам курс: два обрезчика,
 * разойдясь в одном знаке, дали бы курс, который ядро посчитало целым,
 * а экран показал дробным.
 */
export function withoutDivisionTail(value: Amount): Amount {
  return Money.toAmount(Money.format(value, 9));
}

/**
 * Округление до знака вверх. `Money` умеет это делением, и деление на
 * единицу здесь — способ, а не смысл: имя нужно, чтобы на месте вызова
 * читалось округление, а не обратный счёт.
 */
function ceilTo(value: Amount, decimals: number): Amount {
  return Money.divideCeil(value, Money.toAmount('1'), decimals);
}

/**
 * Курс так, как его читают: крупной стороной вперёд и целым числом,
 * пока целое не врёт.
 *
 * Мелкая сторона переворачивается — «1 RUB ≈ 0,0122 USDT» формально то
 * же самое, но числом в сотых долях никто не пользуется и с курсом
 * соседнего обменника его не сравнить, не перевернув в уме.
 *
 * Целое — не округление для вида: курс округляется в ядре и целым же
 * считается, поэтому сумма к выдаче сходится с показанным курсом устно.
 * Но округлять можно ровно до тех пор, пока сдвиг не больше наценки:
 * на восьмидесяти рублях за монету единица — чуть больше процента, а на
 * курсе 1,18 она пятая часть, и целое превратило бы «1,18 USDT за евро»
 * в «1 USDT за 1 EUR» — то есть в обещание, которого сервис не давал.
 * Такой курс остаётся дробным, до сотых.
 *
 * Предел тот же, по которому округляет ядро, но считается он от
 * показанного числа, а не от хранимого: на перевёрнутой стороне это не
 * одно и то же, и разойтись они могут на доли процента. Больше — не
 * могут: обе стороны предела — два процента от величин, отличающихся
 * меньше чем на эти два процента.
 *
 * Направление округления в обоих случаях одно — в пользу сервиса: он не
 * должен обещать больше, чем отдаёт.
 */
export function readRate(rate: Amount, fromCode: string, toCode: string): RateReading {
  const one = Money.toAmount('1');

  // Переворачивать нечего и незачем: делить на ноль нельзя, а такой
  // курс может прийти из старой заявки.
  if (Money.isZero(rate) || Money.isNegative(rate)) {
    return { value: rate, perCode: toCode, unitCode: fromCode };
  }

  const direct = Money.compare(rate, one) >= 0;
  const value = direct ? rate : withoutDivisionTail(Money.divide(one, rate));
  const side = direct
    ? { perCode: toCode, unitCode: fromCode }
    : { perCode: fromCode, unitCode: toCode };

  /*
   * Прямой курс — «сколько получить за единицу отданного», и лишнее
   * отбрасывается вниз. Перевёрнутый — «сколько отдать за единицу
   * полученного», и лишнее добавляется вверх. И то и другое оставляет
   * наценку целой.
   */
  const round = direct ? Money.floor : Money.ceil;
  const whole = round(value);
  const shift = direct ? Money.subtract(value, whole) : Money.subtract(whole, value);

  // Ноль здесь недостижим — крупная сторона всегда не меньше единицы, —
  // и проверять его нечем: сравнение со сдвигом само отсекает случай.
  if (Money.compare(shift, Money.percentOf(value, MAX_ROUNDING_BPS)) <= 0) {
    return { value: whole, ...side };
  }

  return { value: nearUnit(value, direct), ...side };
}

/** Курс около единицы — до сотых и в ту же сторону, что и целое. */
function nearUnit(value: Amount, direct: boolean): Amount {
  return direct
    ? Money.toAmount(Money.format(value, NEAR_UNIT_DIGITS))
    : ceilTo(value, NEAR_UNIT_DIGITS);
}
