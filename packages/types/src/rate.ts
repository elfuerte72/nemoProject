import * as Money from './money.js';
import type { Amount } from './money.js';

/**
 * Как читается курс — одним правилом на весь сервис.
 *
 * Клиент видит его на экране обмена, в сводке перед подачей и в
 * истории; менеджер сверяет с ним то же число в карточке заявки; бот
 * повторяет его в чате. Правило, размноженное по этим местам, разошлось
 * бы молча: курс читают глазами, и «не тот» от «того» отличается только
 * тем, что кто-то заметит.
 *
 * Здесь живёт домен: какая сторона пары называется и каким числом.
 * Вид самого числа — дело каждого приложения: клиент обрезает дробный
 * хвост на восьмом знаке, панель показывает все значащие, и общим
 * оказался бы весь их набор форматов ради одной функции.
 */

/**
 * До какого знака называется курс — до сотых, и на табло, и в ядре.
 *
 * Один шаг на любой курс: и на восьмидесяти рублях за монету, и около
 * единицы. До 28 августа 2026 курс округлялся до целого, пока сдвиг
 * укладывался в наценку, и владелец прочёл это как ошибку: «Rapira
 * минус два процента это 83,79, а в приложении 83» — рубль на монете
 * сверх названных двух процентов. Бат от того же порога мигал между
 * «32» и «32,67» день ото дня.
 */
export const RATE_DIGITS = 2;

export interface RateReading {
  /** Число, которое называют. */
  readonly value: Amount;
  /** Валюта этого числа. */
  readonly perCode: string;
  /** Валюта единицы, за которую его дают: «… за 1 unitCode». */
  readonly unitCode: string;
}

/**
 * Курс словами: число, его валюта и единица, за которую его дают.
 *
 * Здесь же, а не в каждом приложении: сама строка «81 RUB за 1 USDT» —
 * такая же часть правила, как и то, какая сторона называется. Набранная
 * дважды, она разойдётся первой же правкой, и менеджер с клиентом
 * прочтут один курс по-разному — ровно то, ради чего правило и сведено
 * в одно место.
 *
 * Вид числа приложение задаёт своим `digits`: клиент обрезает дробный
 * хвост на восьмом знаке, панель показывает все значащие — и общими им
 * быть незачем.
 */
export function sayRate(
  rate: Amount,
  fromCode: string,
  toCode: string,
  digits: (value: Amount) => string,
): string {
  const reading = readRate(rate, fromCode, toCode);
  return `${digits(reading.value)} ${reading.perCode} за 1 ${reading.unitCode}`;
}

/**
 * Убрать у числа хвост, оставшийся от деления.
 *
 * Курс мельче единицы хранится как частное, и обратное деление
 * возвращает не 82, а 81,999999999999998. Девяти знаков хватает:
 * настоящая дробная часть курса крупнее их на порядки, а шум деления
 * мельче.
 */
function withoutDivisionTail(value: Amount): Amount {
  return Money.toAmount(Money.format(value, 9));
}

/**
 * Округление до знака вверх. `Money` умеет это делением, и деление на
 * единицу здесь — способ, а не смысл: имя нужно, чтобы на месте вызова
 * читалось округление, а не обратный счёт.
 */
function ceilTo(value: Amount, decimals: number): Amount {
  return Money.divideCeil(value, Money.toAmount('1'), decimals);
}

/**
 * Курс так, как его читают: крупной стороной вперёд и до сотых.
 *
 * Мелкая сторона переворачивается — «1 RUB ≈ 0,0122 USDT» формально то
 * же самое, но числом в сотых долях никто не пользуется и с курсом
 * соседнего обменника его не сравнить, не перевернув в уме.
 *
 * Сотые — не округление для вида: ядро округляет курс `roundRate`,
 * который построен на этом же чтении, и до сотых же считает, поэтому
 * сумма к выдаче сходится с показанным курсом на калькуляторе. Чтение
 * округляет и само, потому что курс из заявки, поданной до этого
 * правила, хранит и целое, и длинный дробный хвост, — а читаться он
 * должен так же, как новый.
 *
 * Направление — в пользу сервиса: прямой курс — «сколько получить за
 * единицу отданного», и лишнее отбрасывается вниз; перевёрнутый —
 * «сколько отдать за единицу полученного», и лишнее добавляется вверх.
 * И то и другое оставляет наценку целой.
 */
export function readRate(rate: Amount, fromCode: string, toCode: string): RateReading {
  // Переворачивать нечего и незачем: делить на ноль нельзя, а такой
  // курс может прийти из старой заявки.
  if (Money.isZero(rate) || Money.isNegative(rate)) {
    return { value: rate, perCode: toCode, unitCode: fromCode };
  }

  const { value, direct } = readValue(rate);
  return direct
    ? { value, perCode: toCode, unitCode: fromCode }
    : { value, perCode: fromCode, unitCode: toCode };
}

/**
 * Число курса без подписи: крупная сторона до сотых и то, прямая ли
 * она. Решение «прямой или перевёрнутый» принимается здесь один раз —
 * и чтение, и округление в ядре строятся на нём, а разойдясь на знаке
 * сравнения, они дали бы два разных числа для одного курса.
 */
function readValue(rate: Amount): { value: Amount; direct: boolean } {
  const one = Money.toAmount('1');
  const direct = Money.compare(rate, one) >= 0;
  const large = direct ? rate : withoutDivisionTail(Money.divide(one, rate));
  return { value: toHundredths(large, direct), direct };
}

/** До сотых — вниз у прямого курса, вверх у перевёрнутого. */
function toHundredths(value: Amount, direct: boolean): Amount {
  return direct
    ? Money.toAmount(Money.format(value, RATE_DIGITS))
    : ceilTo(value, RATE_DIGITS);
}

/**
 * Курс, округлённый так, как его называют, — для ядра.
 *
 * Округляется та сторона пары, что больше единицы: у RUB → USDT курс
 * равен 0,0123, и сотые из него — ноль. Поэтому крупная сторона
 * округляется, а мелкая выводится из неё делением и хранится частным —
 * обе стороны остаются согласованными между собой, и `readRate` от
 * округлённого возвращает ровно то число, до которого округляли.
 *
 * Живёт рядом с чтением, а не в ядре: два правила, разойдясь в одном
 * знаке, дали бы курс, который ядро посчитало одним числом, а экран
 * показал другим. Сумма к выдаче считается по этому курсу, и число на
 * экране обязано с ней сходиться.
 */
export function roundRate(rate: Amount): Amount {
  // Нулевой и отрицательный курс округлять нечем: деление на ноль
  // бросает, а до сюда такой курс дойти может — хоть от испорченной
  // котировки, хоть от стопроцентной наценки.
  if (Money.isZero(rate) || Money.isNegative(rate)) return rate;

  const { value, direct } = readValue(rate);
  return direct ? value : Money.divide(Money.toAmount('1'), value);
}
