-- Минимальная сумма обмена задаётся теперь в USDT, а не в рублях: USDT
-- стоит по одну сторону каждого направления, а рубль — только у двух из
-- одиннадцати. Оставить число как есть нельзя: 3000 рублей молча стали
-- бы 3000 USDT и закрыли бы сервис.
--
-- Пересчёт по 85 рублей за USDT — курс на день миграции. Точность здесь
-- не нужна и невозможна: это порог, который администратор задаёт круглым
-- числом и правит из панели. Условие отделяет рублёвый порог от уже
-- пересчитанного: рублёвый начинается с тысяч, а порог в USDT
-- измеряется десятками.
UPDATE "service_settings"
SET "min_exchange_amount" = round("min_exchange_amount" / 85, 0)
WHERE "min_exchange_amount" >= 1000;
