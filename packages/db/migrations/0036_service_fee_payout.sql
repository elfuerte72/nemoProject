-- Сколько сервис удержал по сетке ступеней — в валюте выдачи и на
-- момент подачи.
--
-- Доход по заявке менеджер вписывает руками при исполнении: от него
-- начисляются баллы рефереру, и подтверждать его должен человек. Но
-- подсказать это число панель умела только там, где цена пришла по
-- наценке: у сетки ставка берётся от долларового эквивалента, а курс
-- доллара к валюте выдачи живёт минуту — через день восстановить его
-- нечем. Поэтому оно записывается тогда же, когда курс.
--
-- Колонка пустая, а не с умолчанием: у заявок по наценке доход
-- считается из неё, у наличных без сетки цену называет менеджер, а у
-- поданных до этой колонки числа не было вовсе.
ALTER TABLE "exchange_requests" ADD COLUMN "service_fee_payout" numeric(38, 18);
