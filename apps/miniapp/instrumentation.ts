/**
 * Что делается один раз при запуске сервера.
 *
 * Заводится модуль операций — и вместе с ним источники курса, которые
 * тут же уходят за первой котировкой. Ради этого хук и заведён.
 *
 * Без него правило «прогрев съедает ожидание до прихода первого
 * клиента» не выполнялось: `getCore` ленив и заводится из обработчика
 * маршрута, то есть тем самым первым клиентом. Он открывал Mini App,
 * упирался в биржу и ждал её сам — до трёх секунд по сроку запроса, а на
 * рваном ответе провайдера и дольше, потому что за первой попыткой шли
 * следующие. И повторялось это после каждой выкатки: процесс новый,
 * снимков в памяти нет.
 *
 * Теперь за биржей уходят на старте, до того как откроется приём
 * запросов. Клиент приходит на готовый кэш, и курс у него на экране
 * появляется вместе с экраном.
 */
export async function register(): Promise<void> {
  /*
   * Next зовёт этот хук в каждом рантайме, в котором собрано
   * приложение. Маршруты здесь объявлены `nodejs`, и заводить операции
   * где-то ещё незачем: ни драйвера базы, ни таймеров прогрева там нет.
   */
  if (process.env.NEXT_RUNTIME !== 'nodejs') return;

  try {
    const { getCore } = await import('./lib/core');
    getCore();
  } catch (error) {
    /*
     * Прогрев — ускорение, а не обязанность. Брошенное отсюда уронило бы
     * запуск, и вместо медленного первого клиента вышел бы контейнер,
     * перезапускающийся по кругу. Настоящая поломка — та же нехватка
     * переменной окружения — всё равно проявится на первом же запросе, и
     * там о ней скажут клиенту.
     */
    console.error('Прогрев на старте не удался', error);
  }
}
