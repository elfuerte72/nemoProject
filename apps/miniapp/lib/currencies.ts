/**
 * Что человек знает о валюте помимо её кода: название, место, порядок в
 * списке и флаг для чата.
 *
 * Одно место на приложение и на бота. Добавить валюту в справочник —
 * значит дописать сюда строку; забыть про это можно безнаказанно, но
 * тогда клиент увидит трёхбуквенный код без названия, а в сообщении бота
 * — код без флага.
 *
 * Флагов здесь два вида, и это не дублирование. В приложении флаг
 * нарисован (`app/ui/flags.tsx`): в системных шрифтах Windows флаговых
 * глифов нет, и внутри Mini App вместо Таиланда показались бы две буквы.
 * В сообщении чата рисовать нечем, но и нужды нет: свой набор знаков
 * Telegram везёт с собой сам, и флаг в переписке виден на любой системе.
 *
 * Название и место — не одно и то же, и нужны оба. В строке выбора стоит
 * место: рядом с флагом оно читается одним движением, а «ZAR · ЮАР»
 * узнаётся быстрее, чем «ZAR · Южноафриканский рэнд». Название уходит в
 * подпись для экранного диктора, который флага не видит вовсе.
 *
 * Порядок строк здесь и есть порядок в списке выбора — рубль первым,
 * дальше по алфавиту кода.
 */
const CURRENCIES: Record<string, { name: string; place: string; flag: string }> = {
  RUB: { name: 'Российский рубль', place: 'Россия', flag: '🇷🇺' },
  CNY: { name: 'Китайский юань', place: 'Китай', flag: '🇨🇳' },
  EUR: { name: 'Евро', place: 'Еврозона', flag: '🇪🇺' },
  INR: { name: 'Индийская рупия', place: 'Индия', flag: '🇮🇳' },
  THB: { name: 'Тайский бат', place: 'Таиланд', flag: '🇹🇭' },
  TRY: { name: 'Турецкая лира', place: 'Турция', flag: '🇹🇷' },
  USD: { name: 'Доллар США', place: 'США', flag: '🇺🇸' },
  // У стейблкоина страны нет, и придумывать её нельзя: в столбце мест
  // честнее сказать, что это криптовалюта, а вместо флага поставить
  // монету.
  USDT: { name: 'Tether', place: 'Криптовалюта', flag: '🪙' },
  ZAR: { name: 'Южноафриканский рэнд', place: 'ЮАР', flag: '🇿🇦' },
};

const ORDER = Object.keys(CURRENCIES);

/**
 * Название валюты словами. Незнакомая называется своим кодом: он всё
 * равно стоит рядом, и строка остаётся собранной.
 */
export function currencyName(code: string): string {
  return CURRENCIES[code.toUpperCase()]?.name ?? code;
}

/**
 * Где эта валюта ходит — страна или зона. У незнакомой пусто: строка
 * останется с одним кодом, и это честнее выдуманной страны.
 */
export function currencyPlace(code: string): string {
  return CURRENCIES[code.toUpperCase()]?.place ?? '';
}

/**
 * Флаг для сообщения в чате. У незнакомой валюты — вопросительный знак в
 * рамке: пустое место сдвинуло бы строку столбца влево, и столбец
 * перестал бы читаться сверху вниз.
 */
export function currencyFlag(code: string): string {
  return CURRENCIES[code.toUpperCase()]?.flag ?? '🏳️';
}

/**
 * Порядок валют в списке выбора.
 *
 * Рубль первым — за ним приходит большинство; дальше по алфавиту кода,
 * потому что всякий другой порядок пришлось бы объяснять и пересматривать
 * при каждой новой валюте. Незнакомые уходят в конец: справочник выше в
 * этом файле, и валюта без названия не должна стоять первой.
 */
export function sortCurrencies(codes: readonly string[]): string[] {
  return [...codes].sort((left, right) => {
    const leftIndex = ORDER.indexOf(left.toUpperCase());
    const rightIndex = ORDER.indexOf(right.toUpperCase());
    if (leftIndex === rightIndex) return left.localeCompare(right);
    if (leftIndex === -1) return 1;
    if (rightIndex === -1) return -1;
    return leftIndex - rightIndex;
  });
}
