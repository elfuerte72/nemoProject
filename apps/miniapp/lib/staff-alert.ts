/**
 * Позвать админку разослать сотрудникам то, что только что случилось.
 *
 * Уведомлять сотрудников умеет только панель: шлёт их бот входа, чей
 * токен лежит только в её деплое (docs/adr/0005). Клиентское приложение
 * до него не дотягивается — и не должно, — поэтому оно не отправляет
 * уведомление, а стучится в маршрут панели тем же секретом, каким туда
 * ходит планировщик.
 *
 * Без этого толчка повод доезжает до менеджера за период расписания —
 * минуты. С ним — за секунду, а расписание остаётся страховкой: толчок
 * ничем не гарантирован, и не дошедший ничего не ломает.
 *
 * Ответа никто не ждёт: клиент в этот момент ждёт своего ответа, а
 * поход по сети в чужой деплой к его вопросу отношения не имеет.
 * Поэтому отказ только пишется в журнал.
 */
export function nudgeStaffAlerts(): void {
  const url = process.env.ADMIN_URL;
  const secret = process.env.SCHEDULER_SECRET;
  // Не настроено — не беда: расписание всё равно разошлёт. Молчать об
  // этом всё же нельзя, иначе разница между «панель не настроена» и
  // «менеджеры ничего не получают» видна только по жалобе клиента.
  if (!url || !secret) {
    console.warn('Толчок в панель не настроен: нет ADMIN_URL или SCHEDULER_SECRET');
    return;
  }

  void fetch(`${url.replace(/\/+$/, '')}/api/staff/notify`, {
    method: 'POST',
    headers: { authorization: `Bearer ${secret}` },
  })
    .then((response) => {
      if (!response.ok) {
        console.error('Панель отклонила толчок', response.status);
      }
    })
    .catch((error: unknown) => {
      console.error('Не удалось позвать панель', error);
    });
}
