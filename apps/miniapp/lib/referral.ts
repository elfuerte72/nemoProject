/**
 * Ссылка, по которой клиент зовёт знакомых.
 *
 * Собирается здесь, а не в ядре: адрес бота — свойство развёртывания, и
 * операция, знающая его, перестала бы работать при смене имени бота, не
 * сломавшись при этом заметно.
 *
 * Одна на приложение и на бота: в кабинете её копируют, из чата
 * пересылают — а ведёт она в одно и то же место с одним и тем же
 * параметром, которым выполняется привязка.
 */
export function referralLink(code: string): string | undefined {
  const bot = process.env.NEXT_PUBLIC_TELEGRAM_BOT_USERNAME;
  return bot ? `https://t.me/${bot}?startapp=${code}` : undefined;
}
