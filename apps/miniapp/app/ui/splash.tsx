'use client';

import { useEffect, useRef, useState } from 'react';
import { TobeeMark } from './icons';

/**
 * Заставка при открытии приложения.
 *
 * Показывается сразу и держится свой срок, даже когда сессия открылась
 * быстрее. Раньше было наоборот: она ждала четверть секунды и уходила по
 * ответу сервера — на быстрой сети её не видел никто, и это считалось
 * правильным исходом, потому что вход не должен становиться длиннее
 * ради приветствия.
 *
 * Решение сменилось: приветствие тут и есть смысл экрана. Талисман —
 * то, чем сервис подписан снаружи, и клиент должен его узнать, а не
 * поймать краем глаза. Плата за это честная и известная: вход стал
 * длиннее на срок из `SPLASH_HOLD_MS`, и на быструю сессию эти секунды
 * ложатся целиком.
 *
 * Талисман при этом неподвижен. Двигать его пробовали — подъём и наклон
 * двумя слоями, — и читалось это не полётом, а циклом: путь короткий,
 * период один, и глаз считывает повтор с полутора проходов. Здесь
 * движется свет, а собирается экран очередью: свет, талисман, подпись,
 * строка состояния. Она и работает вместо анимации — заставке нечем
 * зациклиться, потому что нечему ездить.
 *
 * Собрана заставка тем же кадром, что и фирменные полотна: талисман
 * крупно, подпись сервиса под ним. Первое, что видит клиент, и то, чем
 * сервис подписан снаружи, — одно и то же изображение.
 */

export function Splash() {
  const [mascot, setMascot] = useState(false);
  const image = useRef<HTMLImageElement>(null);

  /*
   * Картинка из кэша готова раньше, чем React успевает навесить на неё
   * обработчик, и события о загрузке в этом случае не приходит вовсе —
   * ждать его значит не показать талисмана никогда. А кэш тут правило,
   * а не исключение: Mini App открывают по многу раз, и в первый раз
   * картинку везут, во все остальные — берут с диска.
   *
   * Поэтому спрашиваем и напрямую: готова — показываем сразу.
   */
  useEffect(() => {
    if (image.current?.complete) setMascot(true);
  }, []);

  return (
    <div className="splash" role="status">
      <div className="splash__scene">
        <span className="splash__halo" />
        {/*
          Талисман проступает, а не встаёт готовым: пока его везут, на
          экране светится место, где он появится, и подпись сервиса под
          ним — они нарисованы разметкой и не стоят ничего. Срок показа
          при этом даёт ему фору: на любой рабочей сети семьдесят
          килобайт приезжают задолго до того, как заставка уйдёт.

          Размеры проставлены оба: без них строка подписи прыгает вниз в
          тот момент, когда картинка приехала, — на заставке это
          единственное, что вообще движется не по замыслу.
        */}
        <img
          ref={image}
          className={mascot ? 'splash__mascot splash__mascot--here' : 'splash__mascot'}
          src="/tobee-mascot.webp"
          width={660}
          height={660}
          alt=""
          decoding="async"
          onLoad={() => setMascot(true)}
        />
      </div>
      <span className="splash__wordmark">
        <TobeeMark size={34} />
        <span className="splash__word">
          To<b>bee</b>
        </span>
      </span>
      {/*
        Подпись приходит позже остального: сперва клиент узнаёт, куда
        попал, и только потом — что происходит. Появись обе строки разом,
        читались бы они как одна надпись под картинкой.
      */}
      <span className="splash__note">Открываем сервис</span>
    </div>
  );
}
