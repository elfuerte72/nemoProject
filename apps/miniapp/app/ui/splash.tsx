'use client';

import { useEffect, useState } from 'react';
import { NemoOutline, NemoRim } from './icons';

/**
 * Заставка на время открытия сессии.
 *
 * Появляется не сразу. Сессия открывается за доли секунды, и знак,
 * мигнувший на них, читается не как приветствие, а как сбой отрисовки:
 * человек успевает заметить движение и не успевает понять, что это
 * было. Задержка убирает заставку с быстрой сети целиком — там её никто
 * не увидит, и это правильный исход, а не потерянный показ.
 *
 * Ждать при этом заставка не заставляет: она показывается поверх уже
 * идущего запроса и исчезает, как только он ответил. Ни минимальной
 * длительности, ни «доиграть до конца» — вход не должен становиться
 * длиннее ради того, чтобы оборот знака сошёлся.
 *
 * И потому знак вращается, а не отмеряет один оборот: сколько ждать,
 * приложение не знает, а анимация, кончившаяся посреди загрузки,
 * сообщила бы, что всё замерло.
 */

/**
 * Через сколько заставка появляется. Порог выбран по тому, с чего
 * ожидание становится заметным: до четверти секунды переход читается
 * как мгновенный, и показывать в нём нечего.
 */
const APPEAR_AFTER_MS = 250;

export function Splash() {
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    const timer = setTimeout(() => setVisible(true), APPEAR_AFTER_MS);
    return () => clearTimeout(timer);
  }, []);

  if (!visible) return undefined;

  return (
    <div className="splash" role="status">
      <span className="splash__halo" />
      {/*
        Знак собран из слоёв, а не нарисован один раз.

        Плоскость, повёрнутая в пространстве, на девяноста градусах
        схлопывается в линию — вращается она честно, но выглядит бумагой.
        Здесь у знака есть лицо, изнанка и стопка граней между ними: на
        повороте видно толщину, и он читается жетоном, а не картинкой.

        Изнанка — тот же знак, отражённый: иначе на второй половине
        оборота буква смотрела бы зеркально и читалась как «И».
      */}
      <span className="splash__stage">
        <span className="splash__mark">
          <span className="splash__face splash__face--front">
            <NemoOutline size={76} />
          </span>
          {[0, 1, 2].map((layer) => (
            <span key={layer} className="splash__edge" data-layer={layer}>
              <NemoRim size={76} />
            </span>
          ))}
          <span className="splash__face splash__face--back">
            <NemoOutline size={76} />
          </span>
        </span>
      </span>
      {/*
        Подпись приходит позже знака. На коротком ожидании читать её
        некогда, и она успевала бы только мигнуть; появившись отдельно,
        она сообщает то, ради чего написана: ждать дольше обычного.
      */}
      <span className="splash__note">Открываем сервис</span>
    </div>
  );
}
