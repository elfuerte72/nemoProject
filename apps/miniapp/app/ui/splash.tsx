import type { CSSProperties } from 'react';
import { TOBEE_MARK_BOX, TOBEE_MARK_BRACE, TOBEE_MARK_CELL, TobeeMark } from './icons';

/**
 * Заставка при открытии приложения.
 *
 * Показывается сразу и держится свой срок, даже когда сессия открылась
 * быстрее. Раньше было наоборот: она ждала четверть секунды и уходила по
 * ответу сервера — на быстрой сети её не видел никто, и это считалось
 * правильным исходом, потому что вход не должен становиться длиннее
 * ради приветствия.
 *
 * Решение сменилось: приветствие тут и есть смысл экрана. Плата за это
 * честная и известная: вход стал длиннее на срок из `SPLASH_HOLD_MS`, и
 * на быструю сессию эти секунды ложатся целиком.
 *
 * Герой заставки — знак сервиса, повёрнутый в толщу. Стоял тут
 * талисман, и стоял неподвижно: двигать его пробовали — подъём и наклон
 * двумя слоями, — и читалось это не полётом, а циклом. Путь короткий,
 * период один, и глаз считывает повтор с полутора проходов.
 *
 * У оборота этой беды нет. Замкнутый ход не показывает своего начала:
 * знак поворачивается лицом, торцом, изнанкой и снова лицом, и заметить
 * в этом «опять сначала» не на чем — у круга нет края, о который
 * спотыкается глаз. Оттого и монета, крутящаяся на столе, смотрится
 * дольше, чем качели.
 */

/**
 * Слоёв в толще знака.
 *
 * Объём тут набран стопкой плоских вырезок по контуру знака, и торец —
 * это их рёбра, увиденные под углом. Чем слоёв меньше, тем шире просвет
 * между ними, и в кадре, где знак повёрнут почти боком, толща
 * распадается на гребёнку. Чем больше — тем дороже обходится каждый
 * кадр слабому телефону, а рисуется этот знак на входе, когда устройство
 * и без него занято сборкой первого экрана.
 *
 * Двадцать — там, где просвет уже меньше пикселя, а стопка ещё не стала
 * полусотней слоёв ради кадра, который держится десятую долю секунды.
 */
const SLABS = 20;

/**
 * Толщина знака — доля его же ширины.
 *
 * Знак — пластина, а не брусок: объём должен читаться на повороте, но не
 * превращать сам знак в его собственный торец. Взята чуть тоньше, чем в
 * макете: там знак вылит целиком, а здесь набран слоями, и чем толща
 * больше, тем шире стоят слои и тем заметнее их кромки на повороте.
 */
const DEPTH = 0.15;

/*
 * Форма, по которой вырезан каждый слой.
 *
 * Маска, а не картинка: слой красится своим цветом — лицевой медовый,
 * внутренние торцовые, — и картинка вместо маски заставила бы завести
 * по файлу на оттенок. Контур приходит из `icons.tsx`, оттуда же,
 * откуда его берёт сам знак.
 */
const shape = encodeURIComponent(
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${TOBEE_MARK_BOX.x} ${TOBEE_MARK_BOX.y} ${TOBEE_MARK_BOX.width} ${TOBEE_MARK_BOX.height}"><path fill="#000" fill-rule="evenodd" d="${TOBEE_MARK_BRACE} ${TOBEE_MARK_CELL}"/></svg>`,
);

/*
 * Размеры толщи считаются здесь, а не в стилях.
 *
 * Компоненты в этом приложении несут разметку и классы, а не свои
 * стили, — и здесь единственное исключение, у которого есть причина.
 * В свойство уезжает не оформление: цвета, размеры и сроки лежат в
 * `globals.css`, как и везде. Уезжает форма знака и число слоёв, а они
 * живут в коде — контур в `icons.tsx`, счёт слоёв рядом. Повторённые в
 * стилях, они стали бы второй правдой о том, как выглядит знак, и
 * разошлись бы с первой при ближайшей правке контура.
 */
const markStyle = {
  /* Кавычки одинарные: значение уезжает в атрибут разметки, а двойная
     закрыла бы его на середине. */
  '--mark': `url('data:image/svg+xml,${shape}')`,
  '--mark-ratio': `${TOBEE_MARK_BOX.width} / ${TOBEE_MARK_BOX.height}`,
  /* Шаг между слоями — доля высоты знака: она задана в стилях, потому
     что зависит от ширины окна. */
  '--mark-step': `calc(var(--mark-height) * ${(
    (TOBEE_MARK_BOX.width / TOBEE_MARK_BOX.height) *
    (DEPTH / SLABS)
  ).toFixed(5)})`,
  /* Середина стопки: от неё слои расходятся в обе стороны, и знак
     вращается вокруг своей толщи, а не вокруг лицевой грани. */
  '--mark-mid': (SLABS - 1) / 2,
} as CSSProperties;

/*
 * Крайние слои названы, потому что красятся иначе: лицевая грань —
 * медовая, тем же переходом, каким знак залит везде; изнанка — она же,
 * приглушённая, потому что свет на заставке стоит спереди. Всё, что
 * между ними, — торец.
 */
const slabs = Array.from({ length: SLABS }, (_, index) => {
  if (index === 0) return 'splash__slab splash__slab--face';
  if (index === SLABS - 1) return 'splash__slab splash__slab--back';
  return 'splash__slab';
});

export function Splash({ brief }: { readonly brief?: boolean }) {
  return (
    /*
      Знакомая заставка собирается очередью — свет, знак, подпись, строка
      состояния, — и очередь эта длиннее полутора секунд. При коротком
      показе она не успевает дойти до конца, и приветствие обрывалось бы
      на полуслове: знак проявился наполовину, подписи нет вовсе. Поэтому
      в коротком режиме очереди нет — всё появляется разом и быстро.
    */
    <div className={brief ? 'splash splash--brief' : 'splash'} role="status">
      <div className="splash__scene">
        <span className="splash__halo" />
        {/* Отсвет под знаком — вместо тени на полу: пола тут нет, а
            вес знаку нужен, иначе он висит в пустоте. */}
        <span className="splash__pool" />
        <div className="splash__mark" style={markStyle}>
          {/*
            Узлов у знака четыре, и делят они между собой то, что в
            одиночку не уживается.

            Появление и угасание — оба про прозрачность, и записанные на
            один узел спорили бы за неё. Качание и оборот — оба про
            поворот, и записанные вместе ехали бы одним движением: у CSS
            преобразования не складываются, а применяются по порядку.

            Гаснет знак на ребре: пластина, повёрнутая торцом, почти не
            отражает света, а собранная слоями — ещё и показывает их
            кромки частым гребнем. Приглушённый, этот кадр проходит тем,
            чем он и должен быть: знак повернулся ребром и на миг пропал.
          */}
          <div className="splash__mark-edge">
            <div className="splash__mark-sway">
              <div className="splash__mark-spin">
                {slabs.map((className, index) => (
                  <span
                    key={index}
                    className={className}
                    style={{ '--i': index } as CSSProperties}
                  />
                ))}
                {/* Блик идёт поверх лицевой грани и вспыхивает, пока знак
                    повёрнут лицом: на торце и на изнанке ему не по чему
                    скользить. Полоса отдельным узлом — она едет, а
                    вырезает её по знаку неподвижная маска. */}
                <span className="splash__gleam">
                  <span className="splash__gleam-band" />
                </span>
              </div>
            </div>
          </div>
        </div>
      </div>
      <span className="splash__wordmark">
        <TobeeMark size={34} />
        <span className="splash__word">
          To<b>bee</b>
        </span>
      </span>
      {/*
        Подпись приходит позже остального: сперва клиент узнаёт, куда
        попал, и только потом — что происходит. Появись обе строки разом,
        читались бы они как одна надпись под картинкой.
      */}
      <span className="splash__note">Открываем сервис</span>
    </div>
  );
}
