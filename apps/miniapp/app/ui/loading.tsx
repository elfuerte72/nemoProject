/**
 * Ожидание внутри раздела — талисманом.
 *
 * Строку «загружаем…» он заменяет не ради красоты: словами это
 * сообщают тогда, когда сказать больше нечего, а у сервиса есть кому
 * подождать вместо клиента.
 *
 * Талисман, а не знак с заставки: там приветствие, здесь пауза. Знак
 * поворачивается два с половиной оборота в минуту и требует объёмной
 * сцены — заводить её на каждый переход между разделами значит платить
 * за приветствие там, где здороваться уже не с кем.
 *
 * Картинку в этот момент везут: раньше её показывала заставка, и к
 * первому ожиданию она лежала в кэше, а теперь на заставке знак. Возни
 * с готовностью изображения тут всё равно нет — семьдесят килобайт
 * приезжают внутри той же паузы, которую талисман и обозначает, а
 * пустое место до их прихода прикрыто светом.
 *
 * Появляется с задержкой. Разделы отвечают за доли секунды, и мигнувший
 * на них талисман читался бы сбоем отрисовки — а с задержкой быстрая
 * загрузка проходит вовсе без него, и это правильный исход.
 */
export function Loading() {
  return (
    <div className="loading" role="status">
      <span className="loading__halo" />
      <img
        className="loading__mascot"
        src="/tobee-mascot.webp"
        width={660}
        height={660}
        alt=""
        decoding="async"
      />
      {/* Диктору нужно слово: талисман для него — пустая картинка. */}
      <span className="sr-only">Загружаем…</span>
    </div>
  );
}
