'use client';

/**
 * Раздел, которому нечего показать: запрос не дошёл.
 *
 * Раньше на этом месте стояла одна строка отказа — и всё. Выхода из неё
 * не было никакого: обновить страницу внутри Telegram нечем, и клиенту
 * оставалось закрыть приложение и открыть заново. Между тем причина чаще
 * всего временная — метро, лифт, роуминг, — и лечится она одним
 * нажатием.
 *
 * Кнопка приглушённая, а не медовая: медью в приложении отмечено то,
 * чего сервис ждёт от клиента, — а повторить попытку он не обязан, это
 * не его вина и не его шаг в сделке.
 */
export function Failure({
  message,
  onRetry,
}: {
  readonly message: string;
  readonly onRetry: () => void;
}) {
  return (
    <div className="failure">
      <p className="error">{message}</p>
      <button type="button" onClick={onRetry} className="btn btn--soft failure__retry">
        Попробовать снова
      </button>
    </div>
  );
}
