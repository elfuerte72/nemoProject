import { Onest } from 'next/font/google';
import type { Metadata, Viewport } from 'next';
import type { ReactNode } from 'react';
import './globals.css';

export const metadata: Metadata = {
  title: 'Tobee — обмен валют',
};

export const viewport: Viewport = {
  width: 'device-width',
  initialScale: 1,
  /*
   * Масштабирование не запрещено.
   *
   * Запрет стоял ради iOS: Safari подтягивает страницу, когда фокус
   * уходит в поле мельче шестнадцати пикселей. Но поля здесь и так
   * набраны шестнадцатью и крупнее — сумма вовсе тридцатью двумя, — то
   * есть подтягивать ему нечего, и запрет ничего не защищал.
   *
   * Стоил он при этом дорого: Safari пинч-зум всё равно разрешает, а
   * остальные браузеры запрет исполняют — и человек, которому мелко,
   * увеличить экран не может. Читаемость дороже вёрстки, которая от
   * увеличения не ломается.
   */
  // Нижняя панель садится на область системных жестов, если её не
  // измерить: `env(safe-area-inset-*)` заполняется только при `cover`.
  viewportFit: 'cover',
  // Тот же индиго, что и у фона: Telegram красит им свою полосу над
  // приложением, и любой другой цвет читался бы швом поверх экрана.
  // Значение совпадает с `--bg` в `globals.css` — расходились они на
  // тон, и шов этот был виден именно там, где его и не должно быть.
  themeColor: '#171226',
};

/**
 * Шрифт попадает в сборку, а не тянется с чужого домена: Mini App
 * открывают на любой сети, и лишний круг до стороннего хоста виден
 * прямо в первой отрисовке.
 *
 * Гарнитура здесь та, у которой кириллица нарисована первой, а не
 * следом за латиницей. Стоял Manrope, и русский текст в нём заметно
 * уже латинского: «ж», «щ» и «ю» на сноске в 12,5 пикселя сливаются, а
 * его собственная документация предупреждает о неровном рисунке на
 * малых кеглях в вариативном виде — то есть ровно в том, как шрифт
 * здесь и применён. Onest на настоящих строках приложения шире всего
 * на процент-другой, поэтому вёрстка осталась на месте.
 *
 * Переменная названа по роли, а не по гарнитуре: следующая смена
 * шрифта не должна перебирать стили в двух приложениях.
 */
const ui = Onest({
  subsets: ['latin', 'cyrillic'],
  // Начертания перечислены списком, но шрифт вариативный: на вес
  // сборки их число не влияет — файлы те же самые.
  weight: ['400', '500', '600', '700', '800'],
  variable: '--font-ui',
  display: 'swap',
});

export default function RootLayout({ children }: { children: ReactNode }) {
  return (
    <html lang="ru" className={ui.variable}>
      <head>
        {/*
          Без `async`: данные запуска нужны первому же запросу к серверу,
          и гидрация не должна их дожидаться.
        */}
        <script src="https://telegram.org/js/telegram-web-app.js" />
        {/*
          Талисман объявлен заранее, потому что заставка теперь
          безусловна: он нужен при каждом открытии, и ждать, пока до него
          доберётся React, значит терять на это всю гидрацию. Объявленный
          здесь, он едет с первых миллисекунд разбора страницы.

          Раньше так было нельзя: заставки на быстрой сети не бывало
          вовсе, и объявленная картинка тянулась бы туда, где её никто не
          увидит, — наперегонки с запросом сессии.
        */}
        <link rel="preload" as="image" href="/tobee-mascot.webp" type="image/webp" />
      </head>
      <body>{children}</body>
    </html>
  );
}
