'use client';

import { openTelegram } from '@/lib/telegram/webapp';
import { Sheet } from './ui/sheet';

/**
 * Зарубежные подписки — у партнёра, а не у нас.
 *
 * Netflix, Spotify, ChatGPT русской картой не оплатить, и клиент, который
 * пришёл сюда за батами, спрашивает про них в том же чате. Сервис их не
 * оплачивает: подписка — это счёт у чужого провайдера, продление раз в
 * месяц и возврат при отмене, то есть свой продукт целиком, а не ещё
 * одно направление обмена. Делает его «Оплатишка» — тот же владелец,
 * отдельный сервис, — поэтому здесь стоит не заявка, а дорога к нему.
 *
 * Лист говорит об этом прямо. Иначе клиент решит, что подписку ведёт наш
 * менеджер, и вопросы «где моя подписка» придут туда, где на них нечем
 * ответить.
 *
 * Адрес бота лежит в коде, а не в переменных развёртывания: это не
 * секрет и не свойство контура, а часть того, что сервис предлагает, —
 * ровно как тексты, которыми с клиентом говорит бот. Незаданная
 * переменная оставила бы кнопку, ведущую в никуда.
 */

/** Бот партнёра. Он же ведёт оплату, поддержку и продление. */
const PARTNER_BOT = 'https://t.me/oplatishkaa_bot';

export function SubscriptionsSheet({ onClose }: { readonly onClose: () => void }) {
  return (
    <Sheet title="Оплатить подписку" onClose={onClose}>
      {/*
        Полотно партнёра — его же, каким он подписан снаружи: своя
        нарисованная версия чужого знака была бы второй правдой о том,
        как он выглядит. Размеры проставлены оба, чтобы текст под ним не
        прыгнул в момент, когда картинка приехала.
      */}
      <img
        className="partner__banner"
        src="/oplatishka.webp"
        width={640}
        height={360}
        alt="Оплатишка — зарубежные подписки, оплата в рублях"
        decoding="async"
      />

      <p className="sheet__body">
        «Оплатишка» оплачивает зарубежные подписки — Netflix, Spotify, ChatGPT, Adobe и
        прочее, что не берёт российскую карту. Вы называете сервис, она считает цену,
        выставляет счёт в рублях и платит подписку сама.
      </p>
      <p className="sheet__body">
        Это отдельный сервис: счёт, оплату и продление ведёт он, и спрашивать о подписке
        нужно там же. Здесь остаётся обмен — если для оплаты нужны рубли или USDT, их
        поменяем мы.
      </p>

      <div className="sheet__actions">
        <button
          type="button"
          onClick={() => openTelegram(PARTNER_BOT)}
          className="btn btn--gold"
        >
          Открыть «Оплатишку»
        </button>
      </div>
    </Sheet>
  );
}
