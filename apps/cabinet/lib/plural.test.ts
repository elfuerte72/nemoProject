import { describe, expect, it } from 'vitest';
import { plural } from './plural';

/** Склонение числительного: «1 вызов», «3 вызова», «12 вызовов», «21 вызов». */
describe('склонение', () => {
  const word = (count: number) => plural(count, 'вызов', 'вызова', 'вызовов');

  it('один, несколько, много', () => {
    expect([1, 2, 4, 5, 0].map(word)).toEqual(['вызов', 'вызова', 'вызова', 'вызовов', 'вызовов']);
  });

  it('с одиннадцати по четырнадцать — «много», хоть и кончаются на 1–4', () => {
    expect([11, 12, 14, 111, 114].map(word)).toEqual(Array(5).fill('вызовов'));
  });

  it('после двадцати — снова по последней цифре', () => {
    expect([21, 22, 25, 101, 1003].map(word)).toEqual([
      'вызов',
      'вызова',
      'вызовов',
      'вызов',
      'вызова',
    ]);
  });
});
