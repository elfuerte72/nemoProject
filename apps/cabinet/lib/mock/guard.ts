import { InvalidInputError } from '@nemo/core';
import type { MerchantStatus } from '@nemo/types';

/**
 * Кому можно заводить записи макета.
 *
 * За настоящей заявкой стоит операция ядра, и что мерчанту нельзя,
 * решает она — не спрятанные кнопки. За POS-терминалом операции нет, решать
 * некому, и правило приходится держать здесь: без него мерчант с
 * неподтверждённой почтой или нерассмотренной анкетой заводил бы счета
 * запросом мимо экрана, на который его не пускают.
 *
 * Отключённому тоже нельзя: его открытые заявки доходят до конца, но
 * новое он не начинает — то же правило, что у подачи заявки.
 */
export function requireActiveMerchant(status: MerchantStatus): void {
  if (status !== 'active') {
    throw new InvalidInputError('Кабинет пока не активен: заводить записи нельзя');
  }
}
