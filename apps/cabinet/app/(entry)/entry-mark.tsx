import type { CSSProperties } from 'react';
import { TOBEE_MARK_BOX, TOBEE_MARK_BRACE, TOBEE_MARK_CELL } from '@nemo/brand';

/**
 * Знак сервиса на витрине — повёрнутый в толщу, тот же приём, что на
 * заставке Mini App (`apps/miniapp/app/ui/splash.tsx`).
 *
 * Объём набран стопкой плоских вырезок по контуру знака, а не сценой на
 * WebGL: библиотека трёхмерной графики весит вшестеро больше всего, что
 * страница везёт к первому экрану, а страница эта — дверь, и грузиться
 * ей полагается мгновенно.
 *
 * Отличий от заставки два, и оба от разницы задач. Там знак прикрывает
 * сборку первого экрана и живёт полсекунды-две; здесь он стоит на
 * странице, пока человек читает двери, — поэтому оборот втрое медленнее
 * (`--turn` в стилях) и нет очереди появления: разгорающийся свет
 * хорош один раз при входе, а на странице, куда возвращаются, он читался
 * бы как незаконченная загрузка.
 *
 * Замкнутый ход не показывает своего начала: знак поворачивается лицом,
 * торцом, изнанкой и снова лицом, и «опять сначала» тут не на чем
 * заметить. Оттого монета, крутящаяся на столе, смотрится дольше, чем
 * качели.
 */

/**
 * Слоёв в толще. Меньше — и на кадре, где знак повёрнут почти боком,
 * стопка распадается на гребёнку; больше — дороже каждый кадр, а
 * рисуется знак на входной странице, где ждать никто не намерен.
 */
const SLABS = 20;

/** Толщина знака — доля его ширины: пластина, а не брусок. */
const DEPTH = 0.15;

/*
 * Форма, по которой вырезан каждый слой. Маска, а не картинка: слой
 * красится своим цветом — лицевой медовый, внутренние торцовые, — и
 * картинка вместо маски требовала бы по файлу на оттенок. Контур
 * приходит из `@nemo/brand`, оттуда же, откуда его берёт сам знак.
 */
const shape = encodeURIComponent(
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${TOBEE_MARK_BOX.x} ${TOBEE_MARK_BOX.y} ${TOBEE_MARK_BOX.width} ${TOBEE_MARK_BOX.height}"><path fill="#000" fill-rule="evenodd" d="${TOBEE_MARK_BRACE} ${TOBEE_MARK_CELL}"/></svg>`,
);

/*
 * Размеры толщи считаются здесь, а не в стилях: в свойство уезжает не
 * оформление, а форма знака и число слоёв — они живут в коде. Цвета и
 * сроки лежат в `globals.css`, как и всё остальное оформление.
 */
const markStyle = {
  /* Кавычки одинарные: значение уезжает в атрибут разметки. */
  '--mark': `url('data:image/svg+xml,${shape}')`,
  '--mark-ratio': `${TOBEE_MARK_BOX.width} / ${TOBEE_MARK_BOX.height}`,
  '--mark-step': `calc(var(--mark-height) * ${(
    (TOBEE_MARK_BOX.width / TOBEE_MARK_BOX.height) *
    (DEPTH / SLABS)
  ).toFixed(5)})`,
  /* Середина стопки: от неё слои расходятся в обе стороны, и знак
     вращается вокруг своей толщи, а не вокруг лицевой грани. */
  '--mark-mid': (SLABS - 1) / 2,
} as CSSProperties;

/* Крайние слои красятся иначе: лицо — медовым переходом, изнанка — им
   же, приглушённым: свет стоит спереди. Между ними — торец. */
const slabs = Array.from({ length: SLABS }, (_, index) => {
  if (index === 0) return 'entry__slab entry__slab--face';
  if (index === SLABS - 1) return 'entry__slab entry__slab--back';
  return 'entry__slab';
});

export function EntryMark() {
  return (
    <div className="entry__scene" aria-hidden>
      {/* Свет позади знака — его собственный отблеск, а не подложка. */}
      <span className="entry__halo" />
      <div className="entry__mark" style={markStyle}>
        {/*
          Узлов четыре, и делят они между собой то, что в одиночку не
          уживается: угасание на ребре держит перспективу (прозрачность
          заставляет браузер собрать поддерево в картинку, и схождение
          до слоёв иначе не доходит), качание и оборот — оба про
          поворот, а преобразования не складываются, а применяются по
          порядку.
        */}
        <div className="entry__mark-edge">
          <div className="entry__mark-sway">
            <div className="entry__mark-spin">
              {slabs.map((className, index) => (
                <span
                  key={index}
                  className={className}
                  style={{ '--i': index } as CSSProperties}
                />
              ))}
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}
