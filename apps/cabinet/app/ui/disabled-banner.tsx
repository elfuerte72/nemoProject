import type { MerchantStatus } from '@nemo/types';

/**
 * Полоса «доступ отключён».
 *
 * Стоит над содержимым каждого раздела, а не одним экраном на входе:
 * сказанное однажды к третьему разделу забывается, а кнопок подачи при
 * этом нет — и без объяснения это выглядит поломкой кабинета.
 */
export function DisabledBanner({ status }: { readonly status: MerchantStatus }) {
  if (status !== 'disabled') return null;

  return (
    <p className="banner">
      <b>Доступ отключён.</b> Новые заявки не принимаются, ключи API не работают. Открытые
      заявки доходят до конца — вы видите их здесь. За подробностями — в поддержку.
    </p>
  );
}
