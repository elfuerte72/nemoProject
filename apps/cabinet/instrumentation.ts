/**
 * Что делается один раз при запуске сервера.
 *
 * Заводится модуль операций, а с ним — источники курса, которые тут же
 * уходят за первой котировкой. Правило то же, что в Mini App
 * (`apps/miniapp/instrumentation.ts`): `getCore` ленив, и без этого
 * хука его завёл бы обработчик маршрута — то есть первый мерчант,
 * ожидание которого прогрев и должен съесть. Курс в кабинете виден в
 * разделе «Курсы» и в подаче заявки, и приходить он должен вместе с
 * экраном.
 */
export async function register(): Promise<void> {
  // Next зовёт хук в каждом рантайме, в котором собрано приложение.
  // Маршруты здесь объявлены `nodejs`, и заводить операции где-то ещё
  // незачем: ни драйвера базы, ни таймеров прогрева там нет.
  if (process.env.NEXT_RUNTIME !== 'nodejs') return;

  try {
    const { getCore } = await import('./lib/core');
    getCore();
  } catch (error) {
    // Прогрев — ускорение, а не обязанность: брошенное отсюда уронило
    // бы запуск, и вместо медленного первого запроса вышел бы
    // контейнер, перезапускающийся по кругу.
    console.error('Прогрев на старте не удался', error);
  }
}
