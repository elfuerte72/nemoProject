/**
 * Дробное число из поля ввода — в том виде, в каком его ждёт ядро.
 *
 * Схема денег ядра знает только точку, а экранная клавиатура iPhone с
 * русской раскладкой в поле `inputMode="decimal"` даёт запятую — и в
 * формах панели её набирают и с настоящей клавиатуры: так пишут дроби
 * по-русски. Правило одно на все поля панели, где набирают сумму, курс
 * или ставку: формы настроек нормализовали запятую каждая своей строкой,
 * а карточка заявки не делала этого вовсе — и до 17 сентября 2026
 * дробный доход с телефона не вводился.
 *
 * Меняется только первая запятая: «2,5,5» числом не становится и уходит
 * в ядро отказом, а не другой суммой. Пробел разряда тоже не убирается:
 * «1 000,50» — отказ, а не угаданная тысяча.
 */
export function decimalFromInput(value: string): string {
  return value.replace(',', '.').trim();
}
