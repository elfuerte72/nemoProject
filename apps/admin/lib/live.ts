import type { LiveEvent, LiveTopic } from '@nemo/core';
import { hasUnsentText, LIVE_REFRESH_MS, shouldRefresh, type LiveState } from '@nemo/ui/live';

/*
 * Общее с кабинетом мерчанта — как часто обновляться, когда можно и
 * набрано ли в поле — живёт в `@nemo/ui/live`. Здесь оно реэкспортом,
 * чтобы экраны панели брали всё об обновлении из одного места.
 */
export { hasUnsentText, LIVE_REFRESH_MS, shouldRefresh, type LiveState };

/**
 * Тихое обновление экрана: толчком от сервера, а таймером — вслед.
 *
 * Панель обновлялась только после собственного действия менеджера: новая
 * заявка на открытом экране не появлялась, счётчики в меню застывали, и
 * человек, который сидит и ждёт работу, жал перезагрузку — или решал,
 * что заявок нет.
 *
 * Теперь о событии говорит сам сервер — открытым потоком `/api/live`, и
 * приходит оно за секунду. Таймер при этом остаётся: толчок теряется
 * при обрыве связи и на пересборке подписки, и без таймера потерянное
 * событие означало бы застывший экран до перезагрузки руками. Толчок —
 * ускорение, таймер — обещание.
 *
 * Правило живёт отдельно от разметки и покрыто тестом: «не опрашивать
 * скрытую вкладку» проверяется на живом экране только тем, что кто-то
 * заметит разряженный телефон.
 */

/**
 * Адрес потока событий. Один на всю панель: экран решает сам, его ли
 * это событие, а второе соединение ради второй темы стоило бы вкладке
 * второго открытого сокета.
 */
export const LIVE_STREAM_PATH = '/api/live';

/**
 * Как часто сервер напоминает о себе в молчащий поток. Молчащее
 * соединение закрывают промежуточные узлы, и делают это не сообщая
 * никому: страница осталась бы открытой, а событий в ней больше не
 * появилось бы.
 */
export const LIVE_HEARTBEAT_MS = 30_000;

/**
 * Сколько живёт одно соединение. Браузер откроет его заново сам, а
 * процесс не копит потоки забытых с вечера вкладок.
 */
export const LIVE_STREAM_MAX_MS = 30 * 60_000;

/** Экран, который слушает события: своя тема и, у разговора, свой клиент. */
export interface LiveScreen {
  readonly topic: LiveTopic;
  /** Разговор с одним клиентом. Пусто — экран про всех сразу. */
  readonly clientId?: string | undefined;
}

/**
 * Событие про этот экран или про соседний.
 *
 * Открытая карточка заявки не перечитывает себя оттого, что кто-то
 * написал в переписке, а разговор с одним клиентом — оттого, что
 * написал другой: обновление ради чужого события стоит менеджеру
 * дёрнувшейся страницы под курсором. Список обращений при этом слушает
 * всех: он про всех и есть.
 */
export function eventConcerns(event: LiveEvent, screen: LiveScreen): boolean {
  if (event.topic !== screen.topic) return false;
  if (screen.clientId === undefined) return true;
  return event.clientId === screen.clientId;
}

/**
 * Тем у экрана бывает больше одной.
 *
 * Карточка заявки с лентой переписки внутри — про заявку и про разговор
 * сразу: чек приходит в чат, а перевод отмечает коллега, и застывшее
 * означает «ничего не происходит» ровно до перезагрузки руками. Второй
 * подписки ради второй темы при этом не заводится: соединение на
 * вкладку одно, а какие события его касаются, решает этот список.
 */
export function eventConcernsAny(
  event: LiveEvent,
  screens: readonly LiveScreen[],
): boolean {
  return screens.some((screen) => eventConcerns(event, screen));
}

/** Строка очереди с полем: что в нём сохранено на сервере. */
export interface QueueRowField {
  readonly id: string;
  readonly saved?: string | null | undefined;
}

/**
 * Набрано ли в полях строк очереди то, что ещё не ушло.
 *
 * Тем же правилом, что поле ответа клиенту (`hasUnsentText`): набором
 * считается только набранное поверх сохранённого. И только у строк,
 * которые сейчас в очереди: ушедшая строка унесла своё поле, и ждать его
 * незачем.
 *
 * До 17 сентября 2026 очередь карт считала набором любое непустое поле:
 * номер, сохранённый вместе с переходом, оставался в памяти экрана, и с
 * первого же действия тихое обновление стояло до перезагрузки.
 */
export function rowsHaveUnsentText(
  typed: Readonly<Record<string, string>>,
  rows: readonly QueueRowField[],
): boolean {
  return rows.some((row) => {
    const value = typed[row.id];
    return value !== undefined && hasUnsentText(value, row.saved ?? undefined);
  });
}
