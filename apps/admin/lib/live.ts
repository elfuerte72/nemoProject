/**
 * Тихое обновление очереди.
 *
 * Панель обновлялась только после собственного действия менеджера: новая
 * заявка на открытом экране не появлялась, счётчики в меню застывали, и
 * человек, который сидит и ждёт работу, жал перезагрузку — или решал,
 * что заявок нет.
 *
 * Уведомления о новых заявках приходят сотруднику в Telegram, и это
 * push; обновление экрана — pull. Нужны оба: первое зовёт, второе
 * показывает, а вместе они отвечают на разные вопросы.
 *
 * Правило живёт отдельно от разметки и покрыто тестом: «не опрашивать
 * скрытую вкладку» проверяется на живом экране только тем, что кто-то
 * заметит разряженный телефон.
 */

/**
 * Как часто. Полминуты — верх для того, кто ждёт работу у экрана:
 * дольше он успевает решить, что очередь пуста. Чаще — лишние запросы
 * там, где заявки приходят десятками в день.
 */
export const LIVE_REFRESH_MS = 25_000;

export interface LiveState {
  /** Вкладка скрыта: за фоновые запросы телефон платит батареей. */
  readonly hidden: boolean;
  /** Идёт собственное действие менеджера. */
  readonly busy: boolean;
  /** В форме на экране что-то набрано и ещё не отправлено. */
  readonly typing: boolean;
}

export function shouldRefresh(state: LiveState): boolean {
  return !state.hidden && !state.busy && !state.typing;
}
