/**
 * Ставки в процентах на экране, в базисных пунктах в ядре.
 *
 * Хранит и считает сервис в целых bps: доли процента на дробях уплывают,
 * а деньги от этого расходятся с обещанным. Читает же администратор
 * проценты — «2%», а не «200 bps»: базисный пункт понятен на бирже, а не
 * в форме настроек.
 *
 * Шаг — сотая процента: 0,01% и есть один базисный пункт, мельче
 * ядро не хранит.
 */

/** Базисные пункты → строка процентов для поля ввода. */
export function bpsToPercent(bps: number): string {
  return String(Math.round(bps) / 100);
}

/**
 * Строка процентов → базисные пункты. `null`, когда введено не число:
 * отправлять «2,5,5» в ядро незачем — оно ответит отказом, и менеджер
 * узнает об ошибке ввода из сообщения о неверной ставке.
 */
export function percentToBps(percent: string): number | null {
  const normalized = percent.replace(',', '.').trim();
  if (!/^\d+(\.\d+)?$/.test(normalized)) return null;

  const bps = Number(normalized) * 100;
  // Сотая процента — предел: 0,005% округлилось бы до нуля, и
  // администратор решил бы, что ставка сохранилась.
  return Number.isInteger(bps) ? bps : Math.round(bps);
}
