import { describe, expect, it } from 'vitest';
import { formatAmount, formatDay, formatMoment, formatMoney, formatRate } from './format.js';
import { bpsToPercent, percentToBps } from './percent.js';

describe('сумма для человека', () => {
  it('разделяет разряды: очередь читают глазами', () => {
    expect(formatAmount('5400000')).toBe('5 400 000');
  });

  it('оставляет все значащие знаки после запятой', () => {
    // Восемнадцать знаков — не редкость на криптовалютах, и обрезать
    // их значило бы показать менеджеру не ту сумму, что в базе.
    expect(formatAmount('0.000000000000000001')).toBe('0,000000000000000001');
  });

  it('убирает хвост нулей, которого в сумме нет', () => {
    expect(formatAmount('900.000000')).toBe('900');
  });

  it('ставит код валюты после суммы', () => {
    expect(formatMoney('45000', 'RUB')).toBe('45 000 RUB');
  });
});

describe('время для человека', () => {
  const zone = 'Asia/Yekaterinburg';
  // 3 августа 2026, 15:33 в Тюмени — это 10:33 UTC.
  const now = new Date('2026-08-03T10:33:00Z');

  it('у сегодняшнего показывает час, а не дату: очередь разбирают за сегодня', () => {
    expect(formatMoment(new Date('2026-08-03T00:45:00Z'), now, zone)).toBe('05:45');
  });

  it('считает сутки в поясе менеджера, а не сервера', () => {
    // Та же отметка по UTC — ещё вчерашняя, а на часах менеджера уже
    // наступило следующее утро.
    expect(formatMoment(new Date('2026-08-02T20:10:00Z'), now, zone)).toBe('01:10');
  });

  it('вчерашнее называет словом', () => {
    expect(formatMoment(new Date('2026-08-02T09:00:00Z'), now, zone)).toBe('вчера, 14:00');
  });

  it('давнее показывает датой без года, пока год тот же', () => {
    expect(formatMoment(new Date('2026-07-28T09:00:00Z'), now, zone)).toBe('28 июл.');
  });

  it('добавляет год, когда он не этот: иначе июль читается как ближайший', () => {
    expect(formatMoment(new Date('2025-07-28T09:00:00Z'), now, zone)).toBe('28 июл. 2025 г.');
  });

  it('у случившегося однажды показывает дату без часа', () => {
    expect(formatDay(new Date('2026-08-03T00:45:00Z'), now, zone)).toBe('3 авг.');
  });
});

describe('ставка в процентах', () => {
  it('показывает базисные пункты процентами: администратор читает проценты', () => {
    expect(bpsToPercent(200)).toBe('2');
    expect(bpsToPercent(50)).toBe('0.5');
    expect(bpsToPercent(1)).toBe('0.01');
  });

  it('переводит введённое обратно в пункты', () => {
    expect(percentToBps('2')).toBe(200);
    expect(percentToBps('0,5')).toBe(50);
    expect(percentToBps('12.34')).toBe(1234);
  });

  it('округляет до сотой процента: мельче ядро не хранит', () => {
    expect(percentToBps('0.005')).toBe(1);
  });

  it('отказывается от того, что не число: в ядро уходит ставка, а не опечатка', () => {
    expect(percentToBps('2,5,5')).toBeNull();
    expect(percentToBps('')).toBeNull();
    expect(percentToBps('−1')).toBeNull();
  });
});

/**
 * Курс менеджер сверяет с тем, что видел клиент, и называться он должен
 * так же. Само правило — какая сторона и каким числом — живёт в
 * `@nemo/types` и покрыто там; здесь проверяется, что панель берёт его
 * оттуда, а не набирает строку заново своими словами.
 */
describe('курс в панели', () => {
  it('называет сторону пары, а не голое число', () => {
    expect(formatRate('81', 'USDT', 'RUB')).toBe('81 RUB за 1 USDT');
  });

  it('переворачивает мелкую сторону вместе с подписью', () => {
    expect(formatRate('0.012345679012345679', 'RUB', 'USDT')).toBe('81 RUB за 1 USDT');
  });

  it('ставит разряды своей рукой: курс бывает и в миллионах', () => {
    // Тот же узкий неразрывный пробел, что и в остальных суммах панели.
    expect(formatRate('5224938', 'BTC', 'RUB')).toBe('5\u202f224\u202f938 RUB за 1 BTC');
  });

  it('курс около единицы оставляет дробным', () => {
    expect(formatRate('0.847', 'USDT', 'EUR')).toBe('1,19 USDT за 1 EUR');
  });
});
