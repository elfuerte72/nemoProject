import { describe, expect, it } from 'vitest';
import { suggestServiceIncome } from './income';

/**
 * Подсказка дохода по заявке.
 *
 * Число уходит в реферальные начисления и потом не правится, а менеджер
 * до сих пор считал его в уме. Подсказка — это то же, что уже сделано с
 * курсом: наценка вычтена из котировки при подаче, и здесь она из
 * сделки вынимается обратно.
 */

describe('подсказка дохода', () => {
  /*
   * Клиент отдал 1000 USDT и получил 8100 ₽. Курс, который он видел,
   * уже с наценкой: сервис купил на два процента дешевле, и эти два
   * процента — от того, что он отдал за монеты, а не от выдачи. Отсюда
   * делится на остаток, а не умножается на наценку.
   */
  it('вынимает наценку из полученной клиентом суммы', () => {
    expect(suggestServiceIncome({ amount: '8100', markupBps: 200, side: 'received' })).toBe(
      '165.30',
    );
  });

  /*
   * Та же сделка, но доход называют в отданной валюте. Здесь наценка
   * берётся от суммы прямо: сервис получил 1000 USDT, а отдал столько
   * рублей, сколько стоят 980 из них, — значит заработал двадцать
   * монет, а не 20,4. Одна формула на обе стороны завышала бы этот
   * ответ на саму наценку.
   */
  it('от отданной клиентом суммы берёт наценку прямо', () => {
    expect(suggestServiceIncome({ amount: '1000', markupBps: 200, side: 'given' })).toBe(
      '20.00',
    );
  });

  it('при нулевой наценке даёт ноль', () => {
    expect(suggestServiceIncome({ amount: '8100', markupBps: 0, side: 'received' })).toBe('0');
  });

  it('без суммы ничего не подсказывает', () => {
    expect(suggestServiceIncome({ amount: null, markupBps: 200, side: 'received' })).toBeNull();
  });

  /*
   * Наценка в сто процентов означает курс, по которому клиент не
   * получает ничего: делить на остаток нечем. Такое бывает от опечатки
   * в настройках, и подсказка молчит, а не бросает — менеджер назовёт
   * доход сам.
   */
  it('при наценке во все сто процентов молчит', () => {
    expect(
      suggestServiceIncome({ amount: '8100', markupBps: 10_000, side: 'received' }),
    ).toBeNull();
  });

  /*
   * Копейки в подсказке — шум: доход по рублёвой заявке называют
   * рублями. Но подсказка «ноль» врала бы, поэтому у мелких величин
   * знаки остаются.
   */
  it('мелкую величину не округляет до нуля', () => {
    expect(suggestServiceIncome({ amount: '0.001', markupBps: 200, side: 'received' })).toBe(
      '0.00002040',
    );
  });

  it('отрицательную сумму не считает', () => {
    expect(
      suggestServiceIncome({ amount: '-100', markupBps: 200, side: 'received' }),
    ).toBeNull();
  });
});
