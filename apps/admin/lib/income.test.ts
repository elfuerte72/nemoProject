import { describe, expect, it } from 'vitest';
import { serviceIncomeHint, suggestServiceIncome } from './income';

/**
 * Подсказка дохода по заявке.
 *
 * Число уходит в реферальные начисления и потом не правится, а менеджер
 * до сих пор считал его в уме. Подсказка — это то же, что уже сделано с
 * курсом: наценка вычтена из котировки при подаче, и здесь она из
 * сделки вынимается обратно.
 */

describe('подсказка дохода', () => {
  /*
   * Клиент отдал 1000 USDT и получил 8100 ₽. Курс, который он видел,
   * уже с наценкой: сервис купил на два процента дешевле, и эти два
   * процента — от того, что он отдал за монеты, а не от выдачи. Отсюда
   * делится на остаток, а не умножается на наценку.
   */
  it('вынимает наценку из полученной клиентом суммы', () => {
    expect(suggestServiceIncome({ amount: '8100', markupBps: 200, side: 'received' })).toBe(
      '165.30',
    );
  });

  /*
   * Та же сделка, но доход называют в отданной валюте. Здесь наценка
   * берётся от суммы прямо: сервис получил 1000 USDT, а отдал столько
   * рублей, сколько стоят 980 из них, — значит заработал двадцать
   * монет, а не 20,4. Одна формула на обе стороны завышала бы этот
   * ответ на саму наценку.
   */
  it('от отданной клиентом суммы берёт наценку прямо', () => {
    expect(suggestServiceIncome({ amount: '1000', markupBps: 200, side: 'given' })).toBe(
      '20.00',
    );
  });

  it('при нулевой наценке даёт ноль', () => {
    expect(suggestServiceIncome({ amount: '8100', markupBps: 0, side: 'received' })).toBe('0');
  });

  it('без суммы ничего не подсказывает', () => {
    expect(suggestServiceIncome({ amount: null, markupBps: 200, side: 'received' })).toBeNull();
  });

  /*
   * Наценка в сто процентов означает курс, по которому клиент не
   * получает ничего: делить на остаток нечем. Такое бывает от опечатки
   * в настройках, и подсказка молчит, а не бросает — менеджер назовёт
   * доход сам.
   */
  it('при наценке во все сто процентов молчит', () => {
    expect(
      suggestServiceIncome({ amount: '8100', markupBps: 10_000, side: 'received' }),
    ).toBeNull();
  });

  /*
   * Копейки в подсказке — шум: доход по рублёвой заявке называют
   * рублями. Но подсказка «ноль» врала бы, поэтому у мелких величин
   * знаки остаются.
   */
  it('мелкую величину не округляет до нуля', () => {
    expect(suggestServiceIncome({ amount: '0.001', markupBps: 200, side: 'received' })).toBe(
      '0.00002040',
    );
  });

  it('отрицательную сумму не считает', () => {
    expect(
      suggestServiceIncome({ amount: '-100', markupBps: 200, side: 'received' }),
    ).toBeNull();
  });
});

/**
 * Что подсказать в поле дохода — и подсказывать ли вообще.
 *
 * До 20 сентября 2026 подсказка молчала у всех направлений со
 * ступенчатой сеткой — бат, юань, доллар, евро, — то есть у большей
 * части живого потока: наценки в таком курсе нет, и вынимать из него
 * нечего. Менеджер, закрывающий заявку, видел пустое поле и число,
 * которое поправить потом нельзя.
 */
describe('подсказка дохода: откуда берётся число', () => {
  /** Заявка «рубли → баты» по сетке: удержанное записано при подаче. */
  const bySchedule = {
    incomeCode: 'THB',
    fromCode: 'RUB',
    toCode: 'THB',
    fromAmount: '100000',
    toAmount: '38500',
    requestRate: '0.385',
    feePayout: '1750.25',
    markupBps: 200,
    pricedBySchedule: true,
  };

  it('у цены по сетке подставляет удержанное при подаче', () => {
    expect(serviceIncomeHint(bySchedule)).toEqual({ value: '1750.25', source: 'schedule' });
  });

  /*
   * Ступенчатая комиссия посчитана в валюте выдачи, а курс заявки — уже
   * после неё: пересчитать удержанное в рубли этим курсом значит
   * назвать не ту величину. Число уходит в начисления рефереру, и
   * молчание тут честнее догадки.
   */
  it('в отданной клиентом валюте молчит, а не пересчитывает', () => {
    expect(serviceIncomeHint({ ...bySchedule, incomeCode: 'RUB' })).toBeNull();
  });

  /*
   * Заявка по наценке: удержанного в ней нет, и подсказка считается
   * по-старому — из суммы сделки и наценки сервиса.
   */
  it('у цены по наценке считает её из суммы сделки', () => {
    expect(
      serviceIncomeHint({
        incomeCode: 'RUB',
        fromCode: 'USDT',
        toCode: 'RUB',
        fromAmount: '1000',
        toAmount: '8100',
        requestRate: '8.1',
        feePayout: null,
        markupBps: 200,
        pricedBySchedule: false,
      }),
    ).toEqual({ value: '165.30', source: 'markup' });
  });

  /*
   * Заявка по сетке, поданная до появления колонки, и наличная без
   * сетки: считать нечем ни тем путём, ни другим.
   */
  it('без записанного удержания у цены по сетке молчит', () => {
    expect(serviceIncomeHint({ ...bySchedule, feePayout: null })).toBeNull();
  });

  it('без курса подачи молчит: цену называл менеджер', () => {
    expect(
      serviceIncomeHint({
        ...bySchedule,
        feePayout: null,
        requestRate: null,
        pricedBySchedule: false,
      }),
    ).toBeNull();
  });

  it('нулевое удержание подсказкой не считает', () => {
    expect(serviceIncomeHint({ ...bySchedule, feePayout: '0' })).toBeNull();
  });
});
