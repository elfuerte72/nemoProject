import { botToken } from '@nemo/telegram';

/**
 * Токен бота, чей виджет показывает кнопку входа в админку.
 *
 * Обычно это тот же бот, что у клиентов, — тогда переменная не нужна.
 * Но виджет Telegram Login привязан к домену через `/setdomain`, и один
 * бот держит один домен: клиентское приложение и админка живут на
 * разных, и развернуть их на одном боте не всегда возможно.
 *
 * Разделять токены пришлось потому, что у них разные задачи. Этим
 * проверяется подпись входа — значит, он должен принадлежать боту с
 * кнопкой. `TELEGRAM_BOT_TOKEN` остаётся клиентским: им админка
 * отправляет уведомления, и уйти они должны от бота, которого клиент
 * запускал. Отправка от чужого бота молча не доходит — Telegram не
 * позволяет боту написать первым.
 */
export function loginBotToken(): string {
  return process.env.ADMIN_LOGIN_BOT_TOKEN || botToken();
}
