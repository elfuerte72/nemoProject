/**
 * Предел попыток кода второго фактора.
 *
 * Код шестизначный, и подходят одновременно три — нынешний и два
 * соседних. Без счёта попыток второй шаг входа — это миллион вариантов,
 * которые перебираются со скоростью сети: нужен для этого только
 * пройденный первый шаг, то есть угнанный Telegram сотрудника — ровно
 * тот случай, ради которого второй фактор и заведён. До 17 сентября
 * 2026 предела не было: двадцать пять неверных кодов подряд получали
 * двадцать пять одинаковых отказов.
 *
 * Считается по сотруднику, а не по куке незавершённого входа: куку
 * перебирающий перевыпускает повтором первого шага, и счёт по ней
 * начинался бы заново каждые пять минут. Плата известна: тот, у кого
 * Telegram сотрудника, может на четверть часа закрыть ему вход. Это
 * заметно и лечится сбросом доступа, а подобранный код — нет.
 *
 * Сам счётчик общий с кабинетом (`@nemo/http`) и живёт в памяти
 * процесса: при нескольких процессах панели предел умножается на их
 * число. Правило вынесено из маршрута и покрыто тестом: руками это
 * шесть промахов подряд, а ошибка выглядит как работающий вход.
 */

import { ForbiddenError } from '@nemo/core';
import { createAttemptCounter, isCoreError } from '@nemo/http';

/**
 * Пять промахов за четверть часа. Человеку хватает на опечатку и на
 * код, сменившийся под пальцами; перебирающему это пятнадцать шансов из
 * миллиона за окно.
 */
export const TOTP_ATTEMPT_LIMIT = 5;
export const TOTP_ATTEMPT_WINDOW_MS = 15 * 60_000;

export const TOO_MANY_CODES = 'Слишком много неверных кодов. Попробуйте через четверть часа.';

const counter = createAttemptCounter({
  name: 'nemo.admin.totp-attempts',
  limit: TOTP_ATTEMPT_LIMIT,
  windowMs: TOTP_ATTEMPT_WINDOW_MS,
});

/**
 * Второй шаг входа под счётом попыток.
 *
 * Попытка тратится до ядра, а не по его ответу: перебирающий не ждёт
 * отказа, прежде чем послать следующий код, и сотня кодов, пришедших
 * разом, иначе прошла бы проверку раньше, чем первый успел списаться.
 * Запертому не сверяется и верный код — иначе запирание ничего бы не
 * запирало.
 *
 * Попыткой остаётся только отказ ядра во входе: за недоступную базу
 * закрывать вход на четверть часа значило бы добавить к ней
 * недоступную панель, и такая попытка возвращается. Отказ узнаётся по
 * коду, а не по классу — почему, сказано у `isCoreError`.
 *
 * `onLocked` зовётся один раз — на промахе, исчерпавшем предел, а не на
 * каждом отказе запертому: в журнале панели только ошибки, и строка о
 * закрытом входе должна в нём быть, но перебор не должен его заливать.
 */
export async function withTotpAttempts<T>(
  staffId: string,
  complete: () => Promise<T>,
  now: number = Date.now(),
  onLocked?: () => void,
): Promise<T> {
  const attempt = counter.reserve(staffId, now);
  if (attempt === null) {
    throw new ForbiddenError(TOO_MANY_CODES);
  }

  let result: T;
  try {
    result = await complete();
  } catch (error) {
    if (!isCoreError(error) || error.code !== 'forbidden') {
      counter.release(staffId, now);
    } else if (attempt === TOTP_ATTEMPT_LIMIT) {
      onLocked?.();
    }
    throw error;
  }

  counter.succeeded(staffId);
  return result;
}

/** Забыть всё: нужно тестам, которым иначе мешает предыдущий. */
export function forgetTotpAttempts(): void {
  counter.forget();
}
